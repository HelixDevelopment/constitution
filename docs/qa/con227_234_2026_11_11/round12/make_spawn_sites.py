#!/usr/bin/env python3
"""Spawn-site inventory of the release scripts, round 12: one table row per (script, gate class, program, wrapper,
environment), from the network-spawn gate itself (tests/release/channel_census.py, class Gate: the parser, no lookup
on the host) and the env column of tests/release/channels.tsv. Run from the repository root:
  python3 -I docs/qa/con227_234_2026_11_11/round12/make_spawn_sites.py > docs/qa/con227_234_2026_11_11/round12/spawn_sites.md
Exit 1 when a site is a FINDING or has no table row, so the inventory cannot be produced from a failing tree."""
import collections
import hashlib
import os
import sys

sys.path.insert(0, os.path.join(os.getcwd(), "tests/release"))
import channel_census as cc  # noqa: E402  # pyright: ignore[reportMissingImports]

S = ["scripts/release/derive_release_facts.sh", "scripts/release/redact_cut.sh",
     "scripts/release/tag_and_release.sh", "scripts/release_publish_gitea.sh"]
env = {}
for line in open("tests/release/channels.tsv"):
    if line.startswith("#") or not line.strip():
        continue
    f = line.rstrip("\n").split("\t")
    env[(f[0], f[1], f[2])] = f[4]
g = cc.Gate(S).run()
c = collections.Counter()
bad = 0
for name, line, prog, via, cls, norm in g.sites:
    key = hashlib.sha256(norm.encode()).hexdigest()[:8]
    e = env.get((name, prog, key))
    if cls == "FINDING" or e is None:
        bad += 1
    c[(name, cls, prog, via or "-", e or "NO ROW")] += 1
by_cls = collections.Counter()
for k, n in c.items():
    by_cls[k[1]] += n
print("# Spawn-site inventory, round 12: every program the release scripts run, by gate class")
print()
print("Generated by `make_spawn_sites.py` (beside this file, run from the repository root) from the network-spawn gate")
print("(`tests/release/channel_census.py`, class `Gate`: the bash parser of round 12, no lookup on the host) and the `env`")
print("column of `tests/release/channels.tsv`, over `%s`. The gate that keeps this true is" % "`, `".join(S))
print("`channel_census.py netgate` (parts 2b and 2c of `tests/release/test_channel_census.sh`, and case C53 of the tag,")
print("derive and publish suites); the table is a record, the gate is the check.")
print()
print("Totals: %d sites, %d findings, %d network calls through rc_net, nt or net (the gate's `network_through_rc_net`)."
      % (len(g.sites), len(g.findings), g.n_net))
print()
print("| Gate class | Sites |")
print("|---|---|")
for k in sorted(by_cls):
    print("| `%s` | %d |" % (k, by_cls[k]))
print()
print("| Script | Gate class | Program | Reached via | Environment (channels.tsv) | Sites |")
print("|---|---|---|---|---|---|")
for k in sorted(c, key=lambda k: (k[0], not k[1].startswith("network"), k[1], k[2])):
    print("| %s | `%s` | `%s` | `%s` | `%s` | %d |" % (k + (c[k],)))
sys.exit(1 if bad or g.findings else 0)
