#!/usr/bin/env python3
"""resolve_merge.py <worktree> <last-modified-RFC3339Z>: resolve the text conflicts of merging mainref (2031bc05) into the
Jev S3/S4 vehicle. Every resolution asserts the exact conflict shape it expects (one block per file) and refuses otherwise.
DB / Issues / index / guide census are NOT resolved here (taken from main, then regenerated by their engines)."""
import re, sys, os
wt, lm = sys.argv[1], sys.argv[2]
assert re.fullmatch(r'\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ', lm), lm
B = re.compile(r'^<<<<<<< [^\n]*\n(.*?)^=======\n(.*?)^>>>>>>> [^\n]*\n', re.S | re.M)

def blocks(p):
    t = open(os.path.join(wt, p)).read(); m = list(B.finditer(t)); return t, m

def put(p, t):
    assert not re.search(r'(?m)^(<<<<<<< |>>>>>>> |=======$)', t), p   # line-start markers only (the canon quotes them in text)
    open(os.path.join(wt, p), 'w').write(t)

# 1. post_update_hook.sh: the vehicle's --default-on + rc 5 branch, main's CON-314 runner (trap TTIN TTOU, timeout)
p = 'scripts/post_update_hook.sh'; t, m = blocks(p); assert len(m) == 1, (p, len(m))
ours, theirs = m[0].group(1), m[0].group(2)
assert '--default-on' in ours and "trap '' TTIN TTOU" in theirs and '--default-on' not in theirs
new = theirs.replace('bash "$boot" --non-interactive', 'bash "$boot" --non-interactive --default-on')
assert new.count('--default-on') == 2
t = t[:m[0].start()] + new + t[m[0].end():]
assert '${runner[@]}' not in t and 'local -a runner' not in t, 'stale runner array'
put(p, t)

# 2. cm_jev_detection.sh: main's ONLY change to this file since the merge base (02c10935) is the _run line (TTIN/TTOU
#    ignored for timeout, CON-314); the vehicle restructured the llmctl branch (guarded JEV_LLMCTL_BIN). Resolution = the
#    vehicle's file (HEAD) with main's _run line. Asserted: main's diff since the base touches only that line.
import subprocess
p = 'scripts/gates/cm_jev_detection.sh'
d = subprocess.run(['git', '-C', wt, 'diff', '-U0', '02c10935', 'mainref', '--', p], capture_output=True, text=True, check=True).stdout
chg = [l for l in d.splitlines() if l[:1] in '+-' and not l.startswith(('+++', '---'))]
assert len([l for l in chg if l.startswith('-')]) == 1 and len([l for l in chg if l.startswith('+')]) == 3, chg
t = subprocess.run(['git', '-C', wt, 'show', 'HEAD:' + p], capture_output=True, text=True, check=True).stdout
old = '      if command -v timeout >/dev/null 2>&1; then _run() { timeout --kill-after=2 "$_tmo" "$@"; }; else _run() { "$@"; }; fi\n'
new = ('      # (SIGTTIN/SIGTTOU ignored in a subshell for timeout only: uutils timeout does not ignore them itself and would be\n'
       '      # stopped with a child that touches the terminal, so the limit would never fire; main CON-314)\n'
       "      if command -v timeout >/dev/null 2>&1; then _run() { (trap '' TTIN TTOU; exec timeout --kill-after=2 \"$_tmo\" \"$@\"); }; else _run() { \"$@\"; }; fi\n")
assert t.count(old) == 1; t = t.replace(old, new)
put(p, t)

# 3. CHANGELOG.md: union of both sides' entries, newest date first, vehicle first on a tie (stable)
p = 'CHANGELOG.md'; t, m = blocks(p); assert len(m) == 1, (p, len(m))
def secs(s):
    parts = re.split(r'(?m)^(?=## )', s); assert parts[0].strip() == '', parts[0][:80]
    return [x for x in parts[1:]]
allsec = [(0, i, x) for i, x in enumerate(secs(m[0].group(1)))] + [(1, i, x) for i, x in enumerate(secs(m[0].group(2)))]
def key(e):
    d = re.match(r'## Unreleased — (\d{4}-\d\d-\d\d)', e[2]); assert d, e[2][:80]; return d.group(1)
seen = set(); out = []
for e in sorted(allsec, key=lambda e: (key(e), -e[0], -e[1]), reverse=True):
    if e[2] in seen: continue
    seen.add(e[2]); out.append(e[2] if e[2].endswith('\n\n') else e[2].rstrip('\n') + '\n\n')
put(p, t[:m[0].start()] + ''.join(out) + t[m[0].end():])

# 4. Constitution.md header: Revision 98, Last modified = the landing commit time
p = 'Constitution.md'; t, m = blocks(p); assert len(m) == 1, (p, len(m))
assert '| Revision | 97 |' in m[0].group(1) and '| Revision | 96 |' in m[0].group(2)
new = f'| Revision | 98 |\n| Created | 2026-05-14 |\n| Last modified | {lm} |\n'
put(p, t[:m[0].start()] + new + t[m[0].end():])
print('resolved: post_update_hook.sh cm_jev_detection.sh CHANGELOG.md Constitution.md')
