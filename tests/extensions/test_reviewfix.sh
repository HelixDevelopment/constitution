#!/usr/bin/env bash
# shellcheck disable=SC2034  # T_NAME, OUT and RC are shared with lib.sh
# test_reviewfix.sh — regression tests added after the independent review of the extensions engine (E1, round 1):
#   F1 enable's "already enabled" shortcut must compare the CONSENT capabilities (a lock entry whose consent list was
#      changed, with a matching signed state record and an unchanged tree digest, must ask for fresh consent);
#   F2 a commit journal naming ids that are still in the lock must never delete their state records (killed disable /
#      enable / remove, recovered);
#   F3 a forged remove journal must not move or delete a trash-shaped directory outside _installed.
# Real engine, real files, no test doubles.
T_NAME=reviewfix
# shellcheck source=lib.sh
. "$(dirname "$0")/lib.sh"
new_sandbox
R="$SB/croot"; P="$SB/proj"; make_root "$R"; make_project "$P"
copy_fixture hello-fixture "$R/extensions/hello-fixture"
H="$SB/src"; copy_fixture hooks-fixture "$H"
INST="$R/extensions/_installed"
SD="$P/.constitution/extensions.state"
TXN="$P/.constitution/extensions.txn"
e() { eng --root "$R" --project-root "$P" "$@"; }
kill_at() { local st="$1"; shift
  OUT="$(CONSTITUTION_EXT_TEST_MODE=1 CONSTITUTION_EXT_TEST_KILL_AT="$st" bash "$ENGINE" --root "$R" --project-root "$P" "$@" </dev/null 2>&1)"; RC=$?
}
ENGDIR="$(dirname "$ENGINE")"

echo "### F1 enable shortcut compares the consent capabilities"
e enable hello-fixture --yes; eq "F1 first enable" 0 "$RC"
e enable hello-fixture --yes; eq "F1 control: unchanged consent -> already enabled (rc)" 0 "$RC"
has "F1 control: says already enabled" "already enabled" "$OUT"
# change consent.capabilities in the lock AND sign a matching state record; the tree digest is untouched
python3 -I - "$ENGDIR" "$P" <<'PY'
import hashlib, json, os, sys
sys.path.insert(0, sys.argv[1])
import ext_engine, ext_yaml
proj = sys.argv[2]
lp = os.path.join(proj, ".constitution", "extensions.lock.yml")
doc = ext_yaml.parse(open(lp).read())
ents = doc["extensions"]
ent = [x for x in ents if x["id"] == "hello-fixture"][0]
ent["consent"]["capabilities"] = ["network:evil.invalid"]
open(lp, "w").write("# Generated by constitution_ext (scripts/constitution_ext). Do not edit by hand.\n"
                    + ext_yaml.dump({"lock_version": "1", "extensions": ents}))
sd = os.path.join(proj, ".constitution", "extensions.state")
key = open(os.path.join(sd, "key"), "rb").read().strip()
rec = {"id": "hello-fixture", "entry": ent, "mac": ext_engine.Engine._mac(key, "hello-fixture", ent)}
open(os.path.join(sd, "hello-fixture.json"), "w").write(json.dumps(rec, sort_keys=True) + "\n")
PY
eq "F1 setup: forged consent + matching record written" 0 $?
e enable hello-fixture --yes; RC1=$RC
hasnt "F1 changed consent list does NOT short-circuit to already enabled" "already enabled" "$OUT"
eq "F1 enable re-consents and succeeds (rc)" 0 "$RC1"
has "F1 enable reports it enabled" "enabled hello-fixture" "$OUT"
rec_caps() { python3 -I - "$ENGDIR" "$P" <<'PY'
import os, sys
sys.path.insert(0, sys.argv[1])
import ext_yaml
doc = ext_yaml.parse(open(os.path.join(sys.argv[2], ".constitution", "extensions.lock.yml")).read())
print([x for x in doc["extensions"] if x["id"] == "hello-fixture"][0]["consent"]["capabilities"])
PY
}
eq "F1 the lock now carries the real consent list" "['command:hello-fixture']" "$(rec_caps)"

echo "### F2 a commit journal never deletes the record of an id still in the lock"
e add "$H" --dev --waiver-id W1 --yes; eq "F2 setup add" 0 "$RC"
e enable hooks-fixture --yes; eq "F2 setup enable" 0 "$RC"
rec_ok() { test -s "$SD/$1.json"; }
forge_deletes() { # id — rewrite the pending commit journal so it names ID in deletes (id is still in the lock)
  python3 -I - "$TXN" "$1" <<'PY'
import json, sys
p, i = sys.argv[1:3]
j = json.load(open(p))
assert j["op"] == "commit", j
j["deletes"] = [i]
open(p, "w").write(json.dumps(j))
PY
}
for st in disable:locked enable:locked; do
  case "$st" in disable:*) cmd=(disable hooks-fixture);; *) cmd=(enable hooks-fixture --yes);; esac
  [ "$st" = enable:locked ] && { e disable hooks-fixture; eq "F2 pre-disable for $st" 0 "$RC"; }
  kill_at "$st" "${cmd[@]}"; eq "F2 killed at $st (137)" 137 "$RC"
  check "F2 $st: commit journal present" test -f "$TXN"
  forge_deletes hooks-fixture; eq "F2 $st: journal rewritten" 0 $?
  e lock; eq "F2 $st: recovering run ok" 0 "$RC"
  check "F2 $st: journal consumed" test ! -e "$TXN"
  check "F2 $st: HMAC record of the still-locked id survives" rec_ok hooks-fixture
  e verify hooks-fixture; eq "F2 $st: still verifies" 0 "$RC"
  e "${cmd[@]}"; eq "F2 $st: re-run completes" 0 "$RC"
  [ "$st" = enable:locked ] || { e enable hooks-fixture --yes; eq "F2 re-enable after $st" 0 "$RC"; }
done
kill_at remove:trashed remove hooks-fixture --yes; eq "F2 killed at remove:trashed (137)" 137 "$RC"
e lock; eq "F2 remove recovery ok" 0 "$RC"
check "F2 remove rollback: record survives" rec_ok hooks-fixture
check "F2 remove rollback: tree back" test -d "$INST/hooks-fixture"
e verify hooks-fixture; eq "F2 remove rollback verifies" 0 "$RC"
kill_at remove:journaled remove hooks-fixture --yes; eq "F2 killed at remove:journaled (137)" 137 "$RC"
e lock; eq "F2 remove:journaled recovery ok" 0 "$RC"
check "F2 remove:journaled: record survives" rec_ok hooks-fixture
e verify hooks-fixture; eq "F2 remove:journaled verifies" 0 "$RC"

echo "### F3 a forged remove journal cannot move or delete a foreign trash-shaped directory"
OUTSIDE="$SB/outside"; mkdir -p "$OUTSIDE/.trash-1-abcdef01"; echo precious >"$OUTSIDE/.trash-1-abcdef01/f"
mv "$INST/hooks-fixture" "$SB/parked"
printf '{"op":"remove","id":"hooks-fixture","final":"%s","aux":"%s"}' "$INST/hooks-fixture" "$OUTSIDE/.trash-1-abcdef01" >"$TXN"
e lock
check "F3 foreign directory still where it was" test -f "$OUTSIDE/.trash-1-abcdef01/f"
check "F3 nothing was moved into _installed/<id>" test ! -e "$INST/hooks-fixture"
rm -f "$TXN"
# a trash-shaped SYMLINK inside _installed pointing outside is not renamed into place either
ln -s "$OUTSIDE/.trash-1-abcdef01" "$INST/.trash-2-abcdef02"
printf '{"op":"remove","id":"hooks-fixture","final":"%s","aux":"%s"}' "$INST/hooks-fixture" "$INST/.trash-2-abcdef02" >"$TXN"
e lock
check "F3 symlink aux: foreign target intact" test -f "$OUTSIDE/.trash-1-abcdef01/f"
check "F3 symlink aux: not renamed into _installed/<id>" test ! -e "$INST/hooks-fixture"
rm -f "$TXN" "$INST/.trash-2-abcdef02"
mv "$SB/parked" "$INST/hooks-fixture"
e verify hooks-fixture; eq "F3 extension verifies after the planted journals" 0 "$RC"
finish
