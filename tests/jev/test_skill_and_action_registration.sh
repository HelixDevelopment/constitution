#!/usr/bin/env bash
# tests/jev/test_skill_and_action_registration.sh (design §7.8)
#   A. registry rows JEV_BOOTSTRAP / JEV_STATUS parse and generated slash
#      commands exist and are drift-free against the registry expansion
#   B. skills/jev-decision-layer/register.sh run TWICE against a fixture home
#      yields a single registration per platform (idempotent)
#   C. mcp/jev-decisions.json is valid JSON, declares mcpServers.jev, and is
#      documented as a ${VAR} template (materialized at bootstrap)
# SKIP-with-reason if python3+PyYAML is absent (used only for the yaml parse).
set -uo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
fails=0
say() { printf '[test_skill_action] %s\n' "$*"; }

# ── A. registry rows + generated byte-drift ──────────────────────────────────
if python3 -c 'import yaml' 2>/dev/null; then
  drift=$(python3 - "$REPO" <<'PYEOF'
import sys, yaml, os
repo = sys.argv[1]
reg = yaml.safe_load(open(f'{repo}/actions/registry.yaml'))
acts = {a['name']: a for a in reg['actions']}
problems = []
for name in ('JEV_BOOTSTRAP', 'JEV_STATUS'):
    if name not in acts:
        problems.append(f'{name}: registry row missing'); continue
    a = acts[name]
    for f in ('version','namespaces','slash_bare','slash_conflicts','summary','expansion'):
        if f not in a: problems.append(f'{name}: field {f} missing')
    exp = a['expansion'].strip()
    low = name.lower()
    for plat, ext in (('codex','md'), ('gemini','toml'), ('qwen','toml')):
        for fn in (f'{repo}/actions/generated/{plat}/{low}.{ext}',
                   f'{repo}/actions/generated/{plat}/default-{low}.{ext}'):
            if not os.path.isfile(fn):
                problems.append(f'{name}: generated file missing: {fn}'); continue
            body = open(fn).read()
            if exp not in body:
                problems.append(f'{name}: DRIFT in {fn} (registry expansion not verbatim)')
print('\n'.join(problems))
PYEOF
)
  if [ -z "$drift" ]; then say "A OK: registry rows valid, generated commands drift-free"; else
    say "A FAIL:"; printf '%s\n' "$drift"; fails=$((fails+1)); fi
else
  say "SKIP A: python3+PyYAML absent (registry parse unavailable)"
fi

# ── B. register.sh twice = single registration per fixture platform home ─────
SBX=$(mktemp -d); trap 'rm -rf "$SBX"' EXIT
mkdir -p "$SBX/.claude" "$SBX/.kimi-code" "$SBX/.config/opencode" "$SBX/.pi"
JEV_HOME="$SBX" bash "$REPO/skills/jev-decision-layer/register.sh" >/dev/null 2>&1
JEV_HOME="$SBX" bash "$REPO/skills/jev-decision-layer/register.sh" >/dev/null 2>&1
b_ok=1
[ "$(grep -c '# >>> helix-jev >>>' "$SBX/.kimi-code/config.toml")" = "1" ] || { say "B FAIL: kimi marker block count != 1"; b_ok=0; }
[ "$(jq '[.hooks.PreToolUse[] | .. | .command? // empty | select(test("jev-gate"))] | length' "$SBX/.claude/settings.json")" = "1" ] || { say "B FAIL: claude hook entries != 1"; b_ok=0; }
[ "$(jq '.mcpServers | keys | map(select(.=="jev")) | length' "$SBX/.mcp.json")" = "1" ] || { say "B FAIL: claude mcp jev entries != 1"; b_ok=0; }
jq -e '.mcp.jev' "$SBX/.config/opencode/opencode.json" >/dev/null || { say "B FAIL: opencode mcp.jev missing"; b_ok=0; }
[ -f "$SBX/.config/opencode/jev-coverage-gaps.md" ] || { say "B FAIL: opencode coverage-gap note missing"; b_ok=0; }
[ -f "$SBX/.pi/jev-package.md" ] || { say "B FAIL: pi package note missing"; b_ok=0; }
[ -f "$SBX/.config/jev/registration.stamp" ] || { say "B FAIL: registration stamp missing"; b_ok=0; }
[ -f "$REPO/skills/jev-decision-layer/EXTENSION_SOURCE.yaml" ] || { say "B FAIL: EXTENSION_SOURCE.yaml provenance missing"; b_ok=0; }
# cross-check: the registered home passes CM-JEV-WIRING
if JEV_HOME="$SBX" JEV_DETECTION_FILE="$REPO/scripts/gates/fixtures/jev/evidence/jev-detection.json" \
   bash "$REPO/scripts/gates/cm_jev_wiring.sh" >/dev/null 2>&1; then
  say "B cross-check OK: register.sh output passes CM-JEV-WIRING"
else
  say "B cross-check FAIL: registered home fails CM-JEV-WIRING"; b_ok=0
fi
[ "$b_ok" -eq 1 ] && say "B OK: twice-run = single registration per platform" || fails=$((fails+1))

# ── C. MCP declaration ───────────────────────────────────────────────────────
m="$REPO/mcp/jev-decisions.json"
if jq -e '.mcpServers.jev.command == "python3"' "$m" >/dev/null \
   && jq -e '.mcpServers.jev.args[0] | test("jev_mcp\\.py")' "$m" >/dev/null \
   && grep -q 'TEMPLATE' "$m"; then
  say "C OK: mcp/jev-decisions.json valid, declares jev server, documented as materialization template"
else
  say "C FAIL: mcp/jev-decisions.json invalid or undocumented"; fails=$((fails+1))
fi

if [ "$fails" -eq 0 ]; then say "PASS"; exit 0; fi
say "FAIL ($fails failures)"; exit 1
