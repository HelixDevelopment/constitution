REQ = {"schema": str, "unit": str, "path": str, "sha": str, "tree": str, "runner_hash": str, "verdict": str,
       "reason": str, "verdict_source": str, "rc": int, "secs": (int, float), "known": bool, "leaked": int}


def valid_record(o):
    if not isinstance(o, dict) or o.get("schema") != SCHEMA:
        return False
    for k, t in REQ.items():
        if k not in o or not isinstance(o[k], t) or (t is int and isinstance(o[k], bool)):
            return False
    return o["verdict"] in VERDICTS


def load_results(path):
    recs, invalid = [], 0
    if os.path.exists(path):
        with open(path, "rb") as fh:
            for raw in fh:
                try:
                    o = json.loads(raw.decode("utf-8"))
                except (ValueError, UnicodeDecodeError):
                    invalid += 1
                    continue
                if valid_record(o):
                    recs.append(o)
                else:
                    invalid += 1
    return recs, invalid


def tree_state(root):
    h = hashlib.sha256()
    st = git(root, "status", "--porcelain=v1", "-z", "--untracked-files=all", "--ignore-submodules=none", binary=True)
    h.update(st)
    h.update(git(root, "diff", "HEAD", "--binary", "--no-ext-diff", "--no-color", binary=True, check=False))
    for f in sorted(x for x in git(root, "ls-files", "-o", "--exclude-standard", "-z", binary=True).decode(errors="replace").split("\0") if x):
        h.update(f.encode())
        try:
            with open(os.path.join(root, f), "rb") as fh:
                h.update(hashlib.sha256(fh.read()).digest())
        except OSError:
            h.update(b"?")
    return h.hexdigest()


def load_known(path):
    rows = []
    if not os.path.isfile(path):
        return rows, "absent"
    with open(path, errors="replace") as fh:
        for n, line in enumerate(fh, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            c = line.split("\t")
            if len(c) != 4 or not c[0] or not c[1] or not c[2]:
                raise Fatal(2, "known-failures %s line %d: want 4 TAB columns path, signature, tracked_id, note (first three non-empty)"
                            % (path, n))
            rows.append(c)
    return rows, "%d open row(s)" % len(rows)


def match_known(known, path, reason, logtext):
    for p, sig, tid, _note in known:
        if p != path:
            continue
        if sig.startswith("reason:"):
            if reason == sig[len("reason:"):]:
                return tid
        elif sig in logtext:
            return tid
    return ""


