#!/usr/bin/env python3
"""scripts/full_suite/run_full_suite.py -- engine of the section 11.4.40 full-suite runner.

Invoked through scripts/run_full_suite.sh (python3 -I). Full contract: the header of that
wrapper and docs/guides/full_suite_runner_guide.md. Summary:

* CENSUS: every tracked or untracked-not-ignored file of the repository (git ls-files -co
  --exclude-standard, submodule paths excluded) whose basename matches one of the CANDIDATE
  PATTERNS below is a test file. The census function is checked on every run against a
  built-in fixture tree (positive needle per pattern + decoys + a submodule path); a
  mismatch is exit 3 (instrument blind).
* MANIFEST: config/full_suite_manifest.tsv declares every census file with a class
  (entry | member | fixture), tier (default | heavy) and runner. Census != manifest, or a
  row that breaks a verification rule, is exit 3 (fail closed); nothing runs.
* UNITS: the manifest is turned into a plan of units (path + arguments) for the mode
  (default, or full with --include-heavy). Members of a run_all are never run twice.
* EXECUTION: one unit at a time, nice -n 15 + ionice -c3, own session (process group),
  clean environment (allowlist only), fresh HOME / TMPDIR / XDG_* per unit, own log.
  After the unit, every process that still carries the unit's random token in its
  environment (same group or escaped with setsid) is killed and counted as a leak.
* VERDICT: exit code first; on exit 0 the suite's own terminal summary decides
  (counts with failed>0 => FAIL, zero checks => FAIL, all skipped => SKIP, terminal
  VERDICT/RESULT word). No summary recognised => PASS with verdict_source=exit-code-only.
"""
