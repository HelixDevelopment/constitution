class Fatal(Exception):
    def __init__(self, code, msg):
        Exception.__init__(self, msg)
        self.code = code


def out(msg):
    sys.stdout.write(msg + "\n")
    sys.stdout.flush()


def err(msg):
    sys.stderr.write(msg + "\n")
    sys.stderr.flush()


def git(root, *args, binary=False, check=True):
    p = subprocess.run(["git", "-C", root] + list(args), stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if check and p.returncode != 0:
        raise Fatal(2, "git %s failed: %s" % (" ".join(args), p.stderr.decode(errors="replace").strip()))
    return p.stdout if binary else p.stdout.decode(errors="replace")


# ----------------------------------------------------------------------------- census
def submodule_paths(root):
    p = subprocess.run(["git", "-C", root, "config", "-f", ".gitmodules", "--get-regexp", r"^submodule\..*\.path$"],
                       stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    paths = []
    for line in p.stdout.decode(errors="replace").splitlines():
        parts = line.split(None, 1)
        if len(parts) == 2:
            paths.append(parts[1].strip().rstrip("/"))
    # gitlinks recorded in the index (mode 160000) even without .gitmodules
    for line in git(root, "ls-files", "-s").splitlines():
        if line.startswith("160000 "):
            paths.append(line.split("\t", 1)[1])
    return sorted(set(paths))


def census(root):
    """Return (shpy, gofiles): sorted relative paths of test files; raises Fatal(2) when not a git repo."""
    if subprocess.run(["git", "-C", root, "rev-parse", "--git-dir"], stdout=subprocess.DEVNULL,
                      stderr=subprocess.DEVNULL).returncode != 0:
        raise Fatal(2, "census impossible: %s is not a git work tree" % root)
    subs = submodule_paths(root)
    raw = git(root, "ls-files", "-co", "--exclude-standard", "-z", binary=True).decode(errors="replace")
    shpy, gofiles = [], []
    for f in sorted(set(x for x in raw.split("\0") if x)):
        if any(f == s or f.startswith(s + "/") for s in subs):
            continue
        if not os.path.isfile(os.path.join(root, f)):
            continue  # deleted in the work tree, or a gitlink
        b = os.path.basename(f)
        if any(p.match(b) for p in SH_PATTERNS) or any(p.match(b) for p in PY_PATTERNS):
            shpy.append(f)
        elif GO_PATTERN.match(b):
            gofiles.append(f)
    return shpy, gofiles


def census_needle(scratch):
    """Run census() on a fixture with one positive per pattern, decoys and a submodule path."""
    d = tempfile.mkdtemp(prefix="fsr_needle.", dir=scratch)
    try:
        files = {"a/test_x.sh": 1, "a/y_test.sh": 1, "a/z_selftest.sh": 1, "a/w_selftest_mutations.sh": 1,
                 "a/run_all.sh": 1, "a/test_p.py": 1, "a/q_test.py": 1, "m/k_test.go": 2,
                 "a/testx.sh": 0, "a/test_x.txt": 0, "a/mytest.sh": 0, "a/run_all.sh.bak": 0, "a/k_test.go.orig": 0,
                 "sub/test_in_submodule.sh": 0}
        for f in files:
            os.makedirs(os.path.join(d, os.path.dirname(f)), exist_ok=True)
            with open(os.path.join(d, f), "w") as fh:
                fh.write("x\n")
        env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": d, "GIT_CONFIG_NOSYSTEM": "1"}
        subprocess.run(["git", "init", "-q", d], env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        with open(os.path.join(d, ".gitmodules"), "w") as fh:
            fh.write('[submodule "sub"]\n\tpath = sub\n\turl = x\n')
        shpy, gofiles = census(d)
        want_shpy = sorted(f for f, v in files.items() if v == 1)
        want_go = sorted(f for f, v in files.items() if v == 2)
        if shpy != want_shpy or gofiles != want_go:
            raise Fatal(3, "census instrument blind: needle fixture gave sh/py=%s go=%s, want sh/py=%s go=%s"
                        % (shpy, gofiles, want_shpy, want_go))
    finally:
        rm_tree(d, scratch)


