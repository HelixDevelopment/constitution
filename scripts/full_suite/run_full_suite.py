SAFE_RM = None


def rm_tree(path, scratch):
    """Delete a directory this run created, through scripts/lib/safe_rm.sh (section 11.4.287)."""
    real = os.path.realpath(path)
    sreal = os.path.realpath(scratch)
    if not real.startswith(sreal + os.sep) or not os.path.basename(real).startswith("fsr_"):
        raise Fatal(2, "refusing to delete %s: not a runner-made directory under %s" % (path, scratch))
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "TMPDIR": sreal, "SAFE_RM_ALLOWED_ROOTS": sreal,
           "HOME": os.environ.get("HOME", "/nonexistent")}
    p = subprocess.run(["bash", "-c", '. "$1" || exit 2; safe_rm_rf "$2"', "_", SAFE_RM, real], env=env,
                       stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
    if p.returncode != 0:
        err("WARN: could not remove %s (safe_rm_rf rc=%d): %s" % (real, p.returncode, p.stderr.decode(errors="replace").strip()))


# ----------------------------------------------------------------------------- manifest
def read_text(root, rel):
    try:
        with open(os.path.join(root, rel), errors="replace") as fh:
            return fh.read()
    except OSError:
        return ""


def stem(path):
    b = os.path.basename(path)
    return b.rsplit(".", 1)[0]


def mentions(text, path):
    """True when `text` names the test at `path` (its stem as a whole word, or for a
    *_mutation_test.sh gate its gate stem together with the literal `_mutation_test`)."""
    s = stem(path)
    if re.search(r"(?<![A-Za-z0-9_])" + re.escape(s) + r"(?![A-Za-z0-9_])", text):
        return True
    if s.endswith("_mutation_test"):
        g = s[: -len("_mutation_test")]
        if re.search(r"(?<![A-Za-z0-9_])" + re.escape(g) + r"(?![A-Za-z0-9_])", text) and "_mutation_test" in text:
            return True
    return False


def glob_covers(text, runall, path):
    """True when the run_all loops over test_*.sh / test_*.py of its own directory, the file sits
    in that directory, matches the glob, and its stem is not named on a `continue` line."""
    if os.path.dirname(path) != os.path.dirname(runall):
        return False
    b = os.path.basename(path)
    ext = "sh" if b.endswith(".sh") else "py"
    if not b.startswith("test_") or ("/test_*.%s" % ext) not in text:
        return False
    s = stem(path)
    for line in text.splitlines():
        if "continue" in line and re.search(r"(?<![A-Za-z0-9_])" + re.escape(s) + r"(?![A-Za-z0-9_])", line):
            return False
    return True


def has_own_glob(text, runall, path):
    b = os.path.basename(path)
    ext = "sh" if b.endswith(".sh") else "py"
    return os.path.dirname(path) == os.path.dirname(runall) and ("/test_*.%s" % ext) in text


def covers(text, cover, cover_kind, path):
    """Does the entry `cover` (its text) run the test at `path`? A run_all that loops over its own
    directory's test_*.EXT decides by the glob (honouring `continue` exclusions); otherwise the test
    must be named (stem rule of mentions())."""
    if cover_kind == "runall" and has_own_glob(text, cover, path):
        return glob_covers(text, cover, path)
    return mentions(text, path)


def quick_region(text):
    """Lines of a bash array append that is guarded by `quick` (through the closing paren)."""
    lines, region, inside = text.splitlines(), [], False
    for line in lines:
        if not inside and "quick" in line and "+=(" in line:
            inside = True
        if inside:
            region.append(line)
            if ")" in line.split("+=(", 1)[-1]:
                inside = False
    return "\n".join(region)


def shebang_runner(root, rel):
    first = read_text(root, rel).split("\n", 1)[0]
    if re.match(r"^#!\s*(/bin/sh|/usr/bin/env\s+sh)\s*$", first):
        return "sh"
    return "bash"


def go_module(root, rel):
    d = os.path.dirname(rel)
    while True:
        if os.path.isfile(os.path.join(root, d, "go.mod")):
            return d if d else "."
        if not d:
            return None
        d = os.path.dirname(d)


def generate(root, existing):
    """Heuristic draft; curated rows in `existing` (path -> row) are kept as they are."""
    shpy, gofiles = census(root)
    rows = {}
    runalls = [f for f in shpy if os.path.basename(f) == "run_all.sh" and "/fixtures/" not in "/" + f]
    texts = {r: read_text(root, r) for r in runalls}
    for f in shpy:
        if f in existing:
            rows[f] = existing[f]
            continue
        b = os.path.basename(f)
        kind = "py" if b.endswith(".py") else ("runall" if b == "run_all.sh" else "sh")
        if "/fixtures/" in "/" + f:
            rows[f] = [f, kind, "fixture", "-", "-", "-", "fixture path (not a test entry point)"]
            continue
        tier = "heavy" if HEAVY_NAME.search(b) else "default"
        cover = "-"
        if kind != "runall":
            for r in runalls:
                same = os.path.dirname(r) == os.path.dirname(f)
                gate = f.startswith("scripts/gates/") and f.endswith("_mutation_test.sh")
                if (same or gate) and covers(texts[r], r, "runall", f):
                    cover = r
                    break
            if cover == "-" and kind == "py":
                # a Python test driven by a sibling shell test; a light test is never parked under a heavy driver
                sibs = [s for s in shpy if os.path.dirname(s) == os.path.dirname(f) and s.endswith(".sh")
                        and os.path.basename(s) != "run_all.sh" and os.path.basename(f) in read_text(root, s)
                        and (tier == "heavy" or not HEAVY_NAME.search(os.path.basename(s)))]
                if sibs:
                    cover = sorted(sibs)[0]
        if cover != "-":
            rows[f] = [f, kind, "member", tier, "-", cover, "auto: run by %s" % cover]
        elif kind == "py":
            rows[f] = [f, kind, "entry", tier, "python3", "-", "auto"]
        elif kind == "sh":
            rows[f] = [f, kind, "entry", tier, shebang_runner(root, f), "-", "auto"]
        else:
            rows[f] = [f, kind, "entry", "default", "runall-whole", "-", "auto"]
    # run_all runner: members if it covers a heavy member, else whole
    for r in runalls:
        if r in existing:
            continue
        heavy = [x for x in rows.values() if x[2] == "member" and x[5] == r and x[3] == "heavy"]
        if heavy:
            rows[r][4] = "runall-members"
            rows[r][6] = "auto: covers %d heavy member(s)" % len(heavy)
    for m in sorted(set(go_module(root, g) or ("?" + g) for g in gofiles)):
        if m in existing:
            rows[m] = existing[m]
        elif not m.startswith("?"):
            rows[m] = [m, "go", "entry", "default", "go-test", "-", "auto: Go module with *_test.go"]
    return [rows[k] for k in sorted(rows)]


def read_manifest(path):
    if not os.path.isfile(path):
        raise Fatal(3, "manifest missing: %s (generate with --generate-manifest --write)" % path)
    rows, seen = [], set()
    with open(path, errors="replace") as fh:
        for n, line in enumerate(fh, 1):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            cols = line.split("\t")
            if len(cols) != 7:
                raise Fatal(3, "manifest line %d: want 7 TAB columns, got %d" % (n, len(cols)))
            if cols[0] in seen:
                raise Fatal(3, "manifest line %d: duplicate path %s" % (n, cols[0]))
            seen.add(cols[0])
            rows.append(cols)
    return rows


def verify(root, rows):
    """Return a list of problems (empty = manifest matches census and every rule)."""
    probs = []
    shpy, gofiles = census(root)
    by = {r[0]: r for r in rows}
    gomods = set()
    for g in gofiles:
        m = go_module(root, g)
        if m is None:
            probs.append("unclassifiable: %s has no go.mod ancestor" % g)
        else:
            gomods.add(m)
    want = set(shpy) | gomods
    for f in sorted(want - set(by)):
        probs.append("census file without manifest row: %s" % f)
    for f in sorted(set(by) - want):
        probs.append("stale manifest row (no such test file / module): %s" % f)
    texts = {}
    for path, kind, cls, tier, runner, cover, note in rows:
        o = note.startswith("override:")
        if kind not in KINDS or cls not in CLASSES or tier not in TIERS or runner not in RUNNERS:
            probs.append("%s: value outside closed set (%s/%s/%s/%s)" % (path, kind, cls, tier, runner))
            continue
        b = os.path.basename(path)
        if cls == "fixture":
            if tier != "-" or runner != "-" or cover != "-":
                probs.append("%s: fixture rows take tier/runner/covered_by '-'" % path)
            if "/fixtures/" not in "/" + path and not o:
                probs.append("%s: fixture outside a fixtures/ dir needs an override: note" % path)
            continue
        if tier == "-":
            probs.append("%s: non-fixture row needs tier default|heavy" % path)
        if HEAVY_NAME.search(b) and tier != "heavy" and not o:
            probs.append("%s: heavy-looking name but tier %s (use heavy, or an override: note)" % (path, tier))
        if kind == "go":
            if not (cls == "entry" and runner == "go-test"):
                probs.append("%s: go rows are entry/go-test" % path)
        elif kind == "runall":
            if cls != "entry" or not runner.startswith("runall-"):
                probs.append("%s: run_all rows are entry/runall-*" % path)
        elif cls == "entry":
            if runner not in (("python3",) if kind == "py" else ("bash", "sh")) or cover != "-":
                probs.append("%s: entry %s row has runner %s covered_by %s" % (path, kind, runner, cover))
        if cls == "member":
            if runner != "-":
                probs.append("%s: member rows take runner '-'" % path)
            c = by.get(cover)
            if c is None or c[2] != "entry":
                probs.append("%s: covered_by %s is not an entry row" % (path, cover))
                continue
            t = texts.setdefault(cover, read_text(root, cover))
            if not covers(t, cover, c[1], path):
                probs.append("%s: covered_by %s does not run it (not named, or excluded from its own-dir glob)" % (path, cover))
            if c[3] == "heavy" and tier != "heavy":
                probs.append("%s: member of a heavy entry must be tier heavy" % path)
    for path, kind, cls, tier, runner, cover, note in rows:
        if kind != "runall" or cls != "entry":
            continue
        members = [r for r in rows if r[2] == "member" and r[5] == path]
        heavy = [r for r in members if r[3] == "heavy"]
        t = texts.setdefault(path, read_text(root, path))
        if runner == "runall-whole" and heavy:
            probs.append("%s: runall-whole covers heavy members %s (use runall-quick or runall-members)"
                         % (path, [os.path.basename(r[0]) for r in heavy]))
        if runner == "runall-quick":
            if "--quick" not in t:
                probs.append("%s: runall-quick but the script never mentions --quick" % path)
            q = quick_region(t)
            rest = "\n".join(l for l in t.splitlines() if l not in q.splitlines())
            for r in heavy:
                if not mentions(q, r[0]) or mentions(rest, r[0]):
                    probs.append("%s: heavy member %s is not named only inside the --quick-guarded append, so --quick may still run it"
                                 % (path, os.path.basename(r[0])))
            for r in members:
                if r[3] == "default" and not mentions(rest, r[0]):
                    probs.append("%s: default member %s is named only inside the --quick-guarded append" % (path, os.path.basename(r[0])))
    return probs


def write_manifest(path, rows):
    tmp = path + ".tmp.%d" % os.getpid()
    with open(tmp, "w") as fh:
        fh.write(MANIFEST_HEADER)
        for r in rows:
            fh.write("\t".join(c.replace("\t", " ") for c in r) + "\n")
    os.replace(tmp, path)


# ----------------------------------------------------------------------------- plan
def plan(rows, heavy_mode):
    """Units: list of dicts {id, path, kind, runner, args, tier, run (bool), skip_reason}."""
    by = {r[0]: r for r in rows}
    units = []

    def add(path, runner, args, tier, run, why=""):
        uid = path + ("" if not args else " " + " ".join(args))
        units.append({"id": uid, "path": path, "runner": runner, "args": list(args), "tier": tier, "run": run, "why": why})

    def eff_heavy(r):
        # a member of a heavy entry, or a member of a member, inherits heaviness
        while r[2] == "member":
            if r[3] == "heavy":
                return True
            r = by[r[5]]
        return r[3] == "heavy"

    for r in rows:
        path, kind, cls, tier, runner, cover, note = r
        if cls == "fixture":
            continue
        if cls == "member":
            c = by[cover]
            if c[1] == "runall" and c[4] == "runall-members" and not heavy_mode:
                # the run_all is not run in default mode: its default members run on their own
                if tier == "default":
                    add(path, "python3" if kind == "py" else shebang_runner(ROOT, path), [], tier, True)
                else:
                    add(path, "-", [], tier, False, "heavy_excluded (member of %s)" % cover)
            continue
        if kind == "runall":
            if runner == "runall-quick":
                add(path, "bash", [] if heavy_mode else ["--quick"], tier, True)
            elif runner == "runall-members":
                if heavy_mode:
                    add(path, "bash", [], "heavy", True)
                else:
                    add(path, "-", [], "heavy", False, "heavy_excluded (covers heavy members; default members run alone)")
            else:
                add(path, "bash", [], tier, heavy_mode or tier == "default",
                    "" if heavy_mode or tier == "default" else "heavy_excluded")
            continue
        run = heavy_mode or not eff_heavy(r)
        add(path, runner, [], tier, run, "" if run else "heavy_excluded")
    return units


# ----------------------------------------------------------------------------- verdict parsing
NUM_KEYS = {
    "pass": "p", "passed": "p", "ok": "p", "killed": "p",
    "fail": "f", "failed": "f", "failures": "f", "errors": "f", "survivors": "f", "survived": "f", "failed_suites": "f",
    "skip": "s", "skipped": "s",
    "total": "t", "cases": "t", "checks": "t", "assertions": "t", "tests": "t", "ran": "t",
}
KV = re.compile(r"(?<![A-Za-z0-9_])([A-Za-z_]+)\s*[=:]\s*(\d+)(?![\d.])")
NK = re.compile(r"(?<![A-Za-z0-9_.])(\d+)\s+(passed|failed|ok|skipped|pass|fail|skip|run|PASS|FAIL|SKIP)(?![A-Za-z_])")
RAN = re.compile(r"(?i)\bran\s+(\d+)\s*(?:tests?|test file\(s\)|,)")
CHECKS = re.compile(r"(?i)\b(\d+)\s+check\(s\)\s+passed\b")
WORD = re.compile(r"^\W*(?:[A-Za-z_\-]+\s+)?(RESULT|VERDICT|RUN_ALL|STATUS|SUMMARY)\s*[:=]\s*(PASS|FAIL|SKIP)(?![=\w])(.*)$")
WN = re.compile(r"(?<![A-Za-z0-9_])(passed|failed|skipped)\s+(\d+)(?![\d.])", re.I)
TAIL_LINES = 8
ALLPASS = re.compile(r"^\W*ALL PASS\W*$")


def parse_counts(line):
    c = {}
    for k, v in KV.findall(line):
        key = NUM_KEYS.get(k.lower())
        if key:
            c[key] = c.get(key, 0) + int(v)
    for v, k in NK.findall(line):
        key = {"passed": "p", "pass": "p", "ok": "p", "failed": "f", "fail": "f", "skipped": "s", "skip": "s",
               "run": "t"}.get(k.lower())
        if key and key not in c:
            c[key] = int(v)
    for k, v in WN.findall(line):
        key = {"passed": "p", "failed": "f", "skipped": "s"}[k.lower()]
        if key not in c:
            c[key] = int(v)
    m = RAN.search(line)
    if m and "t" not in c:
        c["t"] = int(m.group(1))
    m = CHECKS.search(line)
    if m and "p" not in c:
        c["p"] = int(m.group(1))
        c.setdefault("f", 0)
    # a counts line must carry a fail count or a total; a lone pass=N is not a summary
    if "f" in c or "t" in c:
        return c
    return None


def judge_exit0(text, kind):
    """Return (verdict, reason, source, counts) for a unit that exited 0."""
    lines = [l.rstrip() for l in text.splitlines() if l.strip()]
    term = lines[-1].strip() if lines else ""
    if kind == "go-test":
        oks = sum(1 for l in lines if re.match(r"^ok\s", l))
        fails = sum(1 for l in lines if re.match(r"^(FAIL|--- FAIL)\b", l))
        if fails:
            return "FAIL", "go_test_reports_failure", "summary", {"p": oks, "f": fails}
        if oks == 0:
            return "FAIL", "zero_checks_run", "summary", {"p": 0, "f": 0}
        return "PASS", "", "summary", {"p": oks, "f": 0}
    m = WORD.match(term)
    if m:
        w, rest = m.group(2), m.group(3)
        if w == "FAIL":
            return "FAIL", "terminal_line_FAIL", "terminal-line", None
        if w == "SKIP":
            r = re.search(r"reason[= ]([A-Za-z0-9_]+)", rest)
            return "SKIP", (r.group(1) if r else "suite_reported_skip"), "terminal-line", None
    counts = None
    for l in reversed(lines[-TAIL_LINES:]):
        counts = parse_counts(l)
        if counts:
            break
    if counts:
        p, f, s = counts.get("p", 0), counts.get("f", 0), counts.get("s", 0)
        t = counts.get("t")
        if f > 0:
            return "FAIL", "summary_reports_failures", "summary", counts
        if (t == 0 and s == 0) or (t is None and "p" in counts and p == 0 and s == 0):
            return "FAIL", "zero_checks_run", "summary", counts
        if p == 0 and s > 0 and (t is None or t <= s):
            return "SKIP", "all_skipped", "summary", counts
        return "PASS", "", "summary", counts
    if m and m.group(2) == "PASS":
        return "PASS", "", "terminal-line", None
    if ALLPASS.match(term):
        return "PASS", "", "terminal-line", None
    if term == "OK" or re.match(r"^OK \(", term):
        return "PASS", "", "terminal-line", None
    return "PASS", "", "exit-code-only", None


def judge(rc, timed_out, text, runner):
    if timed_out:
        return "TIMEOUT", "per_unit_timeout_reached", "runner-timer", None
    if rc < 0:
        return "ERROR", "killed_by_signal_%d" % -rc, "exit-code", None
    if rc == 0:
        return judge_exit0(text, runner)
    if rc == 77:
        lines = [l for l in text.splitlines() if l.strip()]
        r = re.search(r"reason[= ]([A-Za-z0-9_]+)", lines[-1]) if lines else None
        return "SKIP", (r.group(1) if r else "suite_reported_skip"), "exit-code", None
    if rc in (124, 137):
        return "ERROR", "rc_%d_without_runner_timeout" % rc, "exit-code", None
    if rc >= 128:
        return "ERROR", "killed_by_signal_%d" % (rc - 128), "exit-code", None
    if rc in (126, 127):
        return "ERROR", "exec_failed_rc_%d" % rc, "exit-code", None
    return "FAIL", "rc_%d" % rc, "exit-code", None


# ----------------------------------------------------------------------------- execution
def uid_procs():
    me = os.getuid()
    for d in os.listdir("/proc"):
        if d.isdigit():
            try:
                if os.stat("/proc/" + d).st_uid == me:
                    yield int(d)
            except OSError:
                pass


def reap_token(token):
    """Kill every own-uid process whose environment carries the unit token; return the count."""
    needle = ("FULL_SUITE_UNIT_TOKEN=" + token).encode()
    killed = 0
    for _ in range(3):
        found = []
        for pid in uid_procs():
            if pid <= 1 or pid == os.getpid():
                continue
            try:
                with open("/proc/%d/environ" % pid, "rb") as fh:
                    env = fh.read()
            except OSError:
                continue
            if needle in env.split(b"\0"):
                found.append(pid)
        if not found:
            break
        for pid in found:
            assert pid > 1
            try:
                os.kill(pid, signal.SIGKILL)
                killed += 1
            except OSError:
                pass
        time.sleep(0.2)
    return killed


def killpg_checked(pgid, sig):
    # section 11.4.263: never signal a group id <= 1 or our own group
    if not isinstance(pgid, int) or pgid <= 1 or pgid == os.getpgrp():
        raise Fatal(2, "refusing killpg(%r)" % (pgid,))
    try:
        os.killpg(pgid, sig)
    except ProcessLookupError:
        pass


ENV_BASE = ("PATH", "LANG", "LC_ALL", "LC_CTYPE", "TERM", "USER", "LOGNAME", "TZ")


def unit_env(home, token, runner, extras, gomodcache):
    env = {k: os.environ[k] for k in ENV_BASE if k in os.environ}
    env.setdefault("PATH", "/usr/local/bin:/usr/bin:/bin")
    for k in extras:
        if k in os.environ:
            env[k] = os.environ[k]
    tmp = os.path.join(home, "tmp")
    for sub in ("tmp", ".config", ".cache", ".local/share", ".local/state"):
        os.makedirs(os.path.join(home, sub), exist_ok=True)
    env.update({"HOME": home, "TMPDIR": tmp, "XDG_CONFIG_HOME": os.path.join(home, ".config"),
                "XDG_CACHE_HOME": os.path.join(home, ".cache"), "XDG_DATA_HOME": os.path.join(home, ".local/share"),
                "XDG_STATE_HOME": os.path.join(home, ".local/state"), "FULL_SUITE_UNIT_TOKEN": token})
    if runner == "go-test":
        env.update({"GOCACHE": os.path.join(home, ".cache", "go-build"), "GOFLAGS": "-mod=readonly",
                    "GOPROXY": "off", "GOTOOLCHAIN": "local", "GOTELEMETRY": "off"})
        if gomodcache:
            env["GOMODCACHE"] = gomodcache
    return env


def run_unit(u, tmo, log, scratch, extras, gomodcache):
    home = tempfile.mkdtemp(prefix="fsr_home.", dir=scratch)
    token = secrets.token_hex(16)
    env = unit_env(home, token, u["runner"], extras, gomodcache)
    if u["runner"] == "go-test":
        argv, cwd = ["go", "test", "-count=1", "./..."], os.path.join(ROOT, u["path"])
    else:
        argv, cwd = [u["runner"], u["path"]] + u["args"], ROOT
    argv = ["nice", "-n", "15", "ionice", "-c3"] + argv
    t0 = time.time()
    timed_out = False
    with open(log, "wb") as fh:
        proc = subprocess.Popen(argv, cwd=cwd, env=env, stdin=subprocess.DEVNULL, stdout=fh, stderr=subprocess.STDOUT,
                                start_new_session=True)
        pgid = proc.pid
        try:
            rc = proc.wait(timeout=tmo)
        except subprocess.TimeoutExpired:
            timed_out = True
            killpg_checked(pgid, signal.SIGTERM)
            try:
                rc = proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                killpg_checked(pgid, signal.SIGKILL)
                rc = proc.wait()
        except BaseException:
            killpg_checked(pgid, signal.SIGKILL)
            proc.wait()
            reap_token(token)
            rm_tree(home, scratch)
            raise
    secs = round(time.time() - t0, 1)
    leaked = reap_token(token)
    rm_tree(home, scratch)
    return rc, timed_out, secs, leaked, sorted(env)


