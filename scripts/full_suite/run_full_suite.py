                   "# one row; a census file without a row, or a row without a file, makes the runner refuse (exit 3).\n"
                   "# Columns (TAB): path kind class tier runner covered_by note\n"
                   "#   kind    sh | py | go (path = Go module dir) | runall\n"
                   "#   class   entry (run as a unit) | member (run only through covered_by) | fixture (not a test, never run)\n"
                   "#   tier    default | heavy (run only with --include-heavy) | - (fixture)\n"
