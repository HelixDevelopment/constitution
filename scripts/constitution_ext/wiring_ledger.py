"""wiring_ledger.py — ownership ledger, per-root reference file, inventory/adopt/backup/rollback.

Wave 1 of docs/design/extension_engine_ownership_redesign.md (sections 5.1-5.3, 9). Standard library only.
NOTHING here is wired into the installer, the post-update hook or ext_engine.py yet (waves 2+); this is the
tested foundation they will call. Usage:

  python3 -I wiring_ledger.py --project DIR --root DIR <command> [options]
    record  --id ID --producer P --agent A --path REL --kind symlink|file|json-entry [--json-path a.b.0] [--scope project]
    classify --path REL            -> {state: absent|consumer-owned|other-checkout|diverged|ours, replace_ok}
    status                          -> every row with its state
    forget  --id ID                 drop a row (never touches the file)
    rebind  --id ID --old-fingerprint FP   re-fingerprint after OUR OWN replacement (row must still be valid and match FP)
    inventory                       read-only list of items that look constitution-made (nothing is written)
    adopt   [--adopt none|all-matching] [--only REL ...]   record rows for candidates; default adopts NOTHING (D6)
    backup  --path REL ...          copy items + ledger into .constitution-install-backup/<UTC>-wiring/ with a signed manifest
    rollback --backup DIR           restore byte-for-byte; remove rows created after the backup; unlink our links only
    refs add|remove|count|list --id ID [--record-digest D]   per-root reference file extensions/_installed/<id>.refs
  Exit codes: 0 ok, 2 usage, 3 refused (nothing was changed).

Ownership rule (section 5.1): an item is OURS only when (1) a tracked row exists in .constitution/wiring.json,
(2) a locally HMAC-signed row exists in .constitution/extensions.state/wiring.local.json (key = the engine's
per-checkout extensions.state/key, 0600, never committed) and the row's constitution_root equals the current
root realpath, and (3) the on-disk fingerprint equals the row's. Everything else is never replaced or deleted.
Fingerprints: symlink = link text; file = sha256; json-entry = canonical-JSON sha256 of that one entry.
The ledger holds paths and digests only (section 8, §11.4.10). Deletes: unlink of one proven path only, no
recursive delete anywhere (§11.4.287). Time: SOURCE_DATE_EPOCH is honoured for the created stamp (determinism).
"""
