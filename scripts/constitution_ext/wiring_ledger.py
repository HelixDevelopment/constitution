SCHEMA = 1
LEDGER_REL = ".constitution/wiring.json"
STATE_REL = ".constitution/extensions.state"
LOCAL_NAME = "wiring.local.json"
BACKUP_DIR = ".constitution-install-backup"
GITIGNORE_LINES = ("extensions.txn", "*.tmp-*", "extensions.state/")
MARKERS = ("managed-by: constitution_ext", "Generated by scripts/generate_agent_prefix_commands.sh")
HOOK_SUFFIX = "scripts/hooks/action_prefix_expand.sh"
ID_RE = re.compile(r"[a-z0-9][a-z0-9-]{0,62}\Z")
ROW_ID_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}\Z")
AGENT_RE = re.compile(r"[a-z][a-z0-9-]{0,30}\Z")
PRODUCER_RE = re.compile(r"(installer|post-update|adopt|engine:[a-z0-9][a-z0-9-]{0,62})\Z")
KINDS = ("symlink", "file", "json-entry")
JSON_TOK_RE = re.compile(r"[A-Za-z0-9_-]{1,64}\Z")
DIGEST_RE = re.compile(r"[0-9A-Za-z._:-]{1,128}\Z")
ROW_KEYS = ("id", "producer", "agent", "scope", "path", "kind", "json_path", "fingerprint",
            "constitution_root", "created", "constitution_version")
MAX_FILE = 16 * 1024 * 1024
MAX_JSON = 4 * 1024 * 1024
SCAN_DIRS = (".claude/skills", ".agents/skills", "skills", ".kimi-code/skills", ".pi/skills", ".opencode/skills",
             ".opencode/commands", ".pi/prompts", ".gemini/commands", ".qwen/commands", "prompts", ".claude/commands")
AGENT_OF = {".claude": "claude", ".agents": "agents", ".kimi-code": "kimi", ".pi": "pi", ".opencode": "opencode",
            ".gemini": "gemini", ".qwen": "qwen", "skills": "legacy", "prompts": "legacy"}


class Refused(Exception):
    pass


class Usage(Exception):
    pass


def clean(s):
    return "".join(c if c.isprintable() else "?" for c in str(s))[:300]


# ── low-level file helpers ──────────────────────────────────────────────────
def read_nofollow(path, limit, what):
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    except OSError as ex:
        raise Refused("%s unreadable (%s; symlinks are not followed)" % (what, ex.strerror))
    try:
        st = os.fstat(fd)
        if not stat.S_ISREG(st.st_mode):
            raise Refused("%s is not a regular file" % what)
        if st.st_size > limit:
            raise Refused("%s is larger than %d bytes" % (what, limit))
        data = b""
        while True:
            b = os.read(fd, 65536)
            if not b:
                break
            data += b
            if len(data) > limit:
                raise Refused("%s is larger than %d bytes" % (what, limit))
        return data
    finally:
        os.close(fd)


def atomic_write(path, data, mode=0o644):
    """temp in the same directory, fsync, rename; never through a symlink."""
    if os.path.lexists(path) and stat.S_ISLNK(os.lstat(path).st_mode):
        raise Refused("%s is a symlink; refusing to write through it" % path)
    d = os.path.dirname(path)
    tmp = os.path.join(d, ".%s.tmp-%d-%s" % (os.path.basename(path), os.getpid(), os.urandom(4).hex()))
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, mode)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.rename(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    try:
        dfd = os.open(d, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(dfd)
        finally:
            os.close(dfd)
    except OSError:
        pass


def sha_file(path, limit=MAX_FILE):
    return hashlib.sha256(read_nofollow(path, limit, path)).hexdigest()


def canon(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()


def now_iso():
    t = os.environ.get("SOURCE_DATE_EPOCH")
    ts = int(t) if t and t.isdigit() else int(time.time())
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(ts))


def real_dir(path, what):
    if not os.path.isdir(path) or stat.S_ISLNK(os.lstat(path).st_mode) and False:
        raise Refused("%s is not a directory" % what)
    return os.path.realpath(path)


# ── paths ────────────────────────────────────────────────────────────────────
def safe_rel(project_real, rel):
    """Validate a project-relative path: no '', '.', '..', absolute, NUL, .git or ledger-state components, and the
    PARENT must resolve inside the project (the leaf is never followed). Returns the absolute path."""
    if not isinstance(rel, str) or not rel or "\0" in rel or rel.startswith("/") or len(rel) > 1024:
        raise Refused("path %r is not a project-relative path" % clean(rel))
    parts = rel.split("/")
    if any(p in ("", ".", "..") for p in parts) or any(len(p) > 255 for p in parts):
        raise Refused("path %r has an empty, '.' or '..' component" % clean(rel))
    if parts[0] == ".git" or rel == STATE_REL or rel.startswith(STATE_REL + "/") or parts[0] == BACKUP_DIR:
        raise Refused("path %r is reserved" % clean(rel))
    full = os.path.join(project_real, *parts)
    parent_real = os.path.realpath(os.path.dirname(full))
    if parent_real != project_real and not parent_real.startswith(project_real + os.sep):
        raise Refused("path %r resolves outside the project" % clean(rel))
    return full


# ── fingerprints ─────────────────────────────────────────────────────────────
def json_nav(doc, jpath):
    cur = doc
    for tok in jpath.split("."):
        if not JSON_TOK_RE.match(tok):
            raise Refused("json path token %r is not valid" % clean(tok))
        if isinstance(cur, list):
            if not tok.isdigit() or int(tok) >= len(cur):
                return None
            cur = cur[int(tok)]
        elif isinstance(cur, dict):
            if tok not in cur:
                return None
            cur = cur[tok]
        else:
            return None
    return cur


def load_json_file(path, what):
    try:
        return json.loads(read_nofollow(path, MAX_JSON, what).decode("utf-8"))
    except (UnicodeDecodeError, ValueError, RecursionError):
        raise Refused("%s is not valid JSON" % what)


def fingerprint(full, kind, jpath=None):
    """None when the item is absent or is not of the recorded kind."""
    try:
        st = os.lstat(full)
    except OSError:
        return None
    if kind == "symlink":
        return "link:" + os.readlink(full) if stat.S_ISLNK(st.st_mode) else None
    if not stat.S_ISREG(st.st_mode):
        return None
    if kind == "file":
        return "sha256:" + sha_file(full)
    if kind == "json-entry":
        try:
            ent = json_nav(load_json_file(full, "json file"), jpath or "")
        except Refused:
            return None
        return None if ent is None else "json:" + hashlib.sha256(canon(ent)).hexdigest()
    return None


# ── ledger ───────────────────────────────────────────────────────────────────
def constitution_version(root):
    try:
        env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
        env["GIT_CONFIG_NOSYSTEM"] = "1"
        r = subprocess.run(["git", "-C", root, "describe", "--tags", "--abbrev=0", "--match", "helixconstitution-v*"],
                           capture_output=True, text=True, env=env, timeout=20)
        t = r.stdout.strip()
        if r.returncode == 0 and re.fullmatch(r"helixconstitution-v[0-9]+(\.[0-9]+)*", t):
            return t[len("helixconstitution-v"):]
    except (OSError, subprocess.SubprocessError):
        pass
    return "unknown"


class Ledger:
    def __init__(self, project, root):
        self.project = os.path.realpath(project)
        self.root = os.path.realpath(root)
        if not os.path.isdir(self.project):
            raise Refused("project %r is not a directory" % clean(project))
        if not os.path.isdir(self.root):
            raise Refused("root %r is not a directory" % clean(root))
        self.cdir = os.path.join(self.project, ".constitution")
        self.sdir = os.path.join(self.project, STATE_REL)
        self.led = os.path.join(self.project, LEDGER_REL)
        self.loc = os.path.join(self.sdir, LOCAL_NAME)
        self.keyp = os.path.join(self.sdir, "key")

    # -- state dirs / key
    def _need_dir(self, d, create):
        if os.path.lexists(d):
            if not stat.S_ISDIR(os.lstat(d).st_mode):
                raise Refused("%s is not a real directory (a symlink or a file); refusing to use it" % d)
        elif create:
            os.mkdir(d, 0o755 if d == self.cdir else 0o700)

    def key(self, create):
        self._need_dir(self.cdir, create)
        self._need_dir(self.sdir, create)
        if os.path.lexists(self.keyp):
            try:
                fd = os.open(self.keyp, os.O_RDONLY | os.O_NOFOLLOW)
            except OSError as ex:
                raise Refused("state key unreadable: %s" % ex.strerror)
            try:
                st = os.fstat(fd)
                if not stat.S_ISREG(st.st_mode) or st.st_mode & 0o077:
                    raise Refused("state key must be a regular file with mode 0600")
                k = os.read(fd, 256).strip()
            finally:
                os.close(fd)
            if not re.fullmatch(rb"[0-9a-f]{64}", k):
                raise Refused("state key is malformed")
            return k
        if not create:
            return None
        k = os.urandom(32).hex().encode()
        fd = os.open(self.keyp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        with os.fdopen(fd, "wb") as f:
            f.write(k + b"\n")
            f.flush()
            os.fsync(f.fileno())
        return k

    def ensure_gitignore(self):
        gi = os.path.join(self.cdir, ".gitignore")
        have = []
        if os.path.lexists(gi):
            have = read_nofollow(gi, 65536, "gitignore").decode("utf-8", "replace").splitlines()
        missing = [ln for ln in GITIGNORE_LINES if ln not in have]
        if missing:
            atomic_write(gi, ("\n".join(have + missing) + "\n").encode())

    # -- tracked ledger
    @staticmethod
    def _row_ok(r):
        if not isinstance(r, dict) or set(r) - set(ROW_KEYS) or any(k not in r for k in ROW_KEYS if k != "json_path"):
            raise Refused("ledger row has missing or unknown fields")
        if not all(isinstance(r[k], str) for k in r):
            raise Refused("ledger row has a non-string field")
        if not ROW_ID_RE.match(r["id"]) or not PRODUCER_RE.match(r["producer"]) or not AGENT_RE.match(r["agent"]):
            raise Refused("ledger row %r has an invalid id, producer or agent" % clean(r["id"]))
        if r["scope"] != "project" or r["kind"] not in KINDS:
            raise Refused("ledger row %r has an invalid scope or kind" % clean(r["id"]))
        parts = r["path"].split("/")
        if r["path"].startswith("/") or any(p in ("", ".", "..") for p in parts) or "\0" in r["path"]:
            raise Refused("ledger row %r has a hostile path" % clean(r["id"]))
        if r["kind"] == "json-entry" and not r.get("json_path"):
            raise Refused("ledger row %r is a json-entry without json_path" % clean(r["id"]))
        return r

    def load(self):
        if not os.path.lexists(self.led):
            return []
        try:
            doc = json.loads(read_nofollow(self.led, MAX_JSON, "wiring ledger").decode("utf-8"))
        except (UnicodeDecodeError, ValueError, RecursionError):
            raise Refused("wiring ledger %s is not valid JSON; refusing everything (nothing changed)" % LEDGER_REL)
        if not isinstance(doc, dict) or doc.get("schema") != SCHEMA or not isinstance(doc.get("rows"), list) \
                or set(doc) - {"schema", "rows"}:
            raise Refused("wiring ledger has an unknown shape; refusing everything (nothing changed)")
        rows, seen = [], set()
        for r in doc["rows"]:
            self._row_ok(r)
            if r["id"] in seen:
                raise Refused("wiring ledger has a duplicate id %r" % clean(r["id"]))
            seen.add(r["id"])
            rows.append(r)
        return rows

    def save(self, rows):
        self._need_dir(self.cdir, True)
        rows = sorted(rows, key=lambda r: r["id"])
        atomic_write(self.led, (json.dumps({"schema": SCHEMA, "rows": rows}, indent=1, sort_keys=True) + "\n").encode())

    # -- local signed file
    @staticmethod
    def row_digest(row):
        return hashlib.sha256(canon(row)).hexdigest()

    @staticmethod
    def _mac(key, rows):
        return hmac.new(key, b"wiring-local\0" + canon(rows), hashlib.sha256).hexdigest()

    def local_rows(self):
        """{id: digest} that carry a valid signature; {} when absent, malformed or forged (never raises)."""
        try:
            key = self.key(False)
            if key is None or not os.path.lexists(self.loc):
                return {}
            doc = json.loads(read_nofollow(self.loc, MAX_JSON, "local wiring file").decode("utf-8"))
            rows = doc.get("rows")
            if doc.get("schema") != SCHEMA or not isinstance(rows, dict) or not isinstance(doc.get("mac"), str) \
                    or not all(isinstance(k, str) and isinstance(v, str) for k, v in rows.items()):
                return {}
            if not hmac.compare_digest(doc["mac"], self._mac(key, rows)):  # RULE:W-local-mac
                return {}
            return rows
        except (Refused, ValueError, RecursionError, UnicodeDecodeError, AttributeError):
            return {}

    def save_local(self, rows):
        key = self.key(True)
        self.ensure_gitignore()
        atomic_write(self.loc, (json.dumps({"schema": SCHEMA, "rows": rows, "mac": self._mac(key, rows)},
                                           indent=1, sort_keys=True) + "\n").encode(), 0o600)

    # -- ownership
    def classify_row(self, row, local):
        full = safe_rel(self.project, row["path"])
        if not os.path.lexists(full):
            return "absent"
        if local.get(row["id"]) != self.row_digest(row) or row["constitution_root"] != self.root:  # RULE:W-root-binding
            return "other-checkout"
        if fingerprint(full, row["kind"], row.get("json_path")) != row["fingerprint"]:  # RULE:W-fingerprint
            return "diverged"
        return "ours"

    def classify(self, rel):
        full = safe_rel(self.project, rel)
        rows = [r for r in self.load() if r["path"] == rel]
        if not os.path.lexists(full):
            return {"path": rel, "state": "absent", "replace_ok": False, "rows": [r["id"] for r in rows]}
        if not rows:
            return {"path": rel, "state": "consumer-owned", "replace_ok": False, "rows": []}
        local = self.local_rows()
        states = [self.classify_row(r, local) for r in rows]
        for s in ("other-checkout", "diverged"):
            if s in states:
                return {"path": rel, "state": s, "replace_ok": False, "rows": [r["id"] for r in rows]}
        return {"path": rel, "state": "ours", "replace_ok": True, "rows": [r["id"] for r in rows]}

    def make_row(self, rid, producer, agent, rel, kind, jpath=None, scope="project"):
        if not ROW_ID_RE.match(rid or ""):
            raise Refused("row id %r is not valid" % clean(rid))
        if not PRODUCER_RE.match(producer or ""):
            raise Refused("producer %r is not one of installer, post-update, adopt, engine:<id>" % clean(producer))
        if not AGENT_RE.match(agent or ""):
            raise Refused("agent %r is not valid" % clean(agent))
        if scope != "project":
            raise Refused("scope %r is not supported yet (user-scope rows arrive with the installer wave)" % clean(scope))
        if kind not in KINDS:
            raise Refused("kind %r is not one of %s" % (clean(kind), ", ".join(KINDS)))
        full = safe_rel(self.project, rel)
        if kind == "json-entry" and not jpath:
            raise Refused("kind json-entry needs --json-path")
        if kind != "json-entry" and jpath:
            raise Refused("--json-path is only for kind json-entry")
        fp = fingerprint(full, kind, jpath)
        if fp is None:
            raise Refused("%s is absent or is not a %s; nothing to record" % (clean(rel), kind))
        row = {"id": rid, "producer": producer, "agent": agent, "scope": scope, "path": rel, "kind": kind,
               "fingerprint": fp, "constitution_root": self.root, "created": now_iso(),
               "constitution_version": constitution_version(self.root)}
        if jpath:
            row["json_path"] = jpath
        return row

    def record(self, rid, producer, agent, rel, kind, jpath=None, scope="project"):
        rows = self.load()
        old = [r for r in rows if r["id"] == rid]
        new = self.make_row(rid, producer, agent, rel, kind, jpath, scope)
        for r in rows:
            if r["id"] != rid and r["path"] == rel and (kind != "json-entry" or r.get("json_path") == jpath
                                                         or r["kind"] != "json-entry"):
                raise Refused("path %s is already recorded under id %s" % (clean(rel), clean(r["id"])))
        if old:
            o = dict(old[0])
            if all(o.get(k) == new.get(k) for k in ("producer", "agent", "scope", "path", "kind", "json_path",
                                                    "fingerprint", "constitution_root")):
                if self.local_rows().get(rid) == self.row_digest(o):
                    return {"id": rid, "fingerprint": o["fingerprint"], "changed": False}
                new["created"], new["constitution_version"] = o["created"], o["constitution_version"]
            else:
                raise Refused("id %s is already recorded for a different item; forget it first" % clean(rid))
        rows = [r for r in rows if r["id"] != rid] + [new]
        # launder nothing: keep only the signatures that were valid, then add this one
        keep = {r["id"]: self.row_digest(r) for r in rows if r["id"] != rid
                and self.local_rows().get(r["id"]) == self.row_digest(r)}
        keep[rid] = self.row_digest(new)
        self.save(rows)
        self.save_local(keep)
        return {"id": rid, "fingerprint": new["fingerprint"], "changed": True}

    def forget(self, rid):
        rows = self.load()
        if not any(r["id"] == rid for r in rows):
            raise Refused("no row with id %s" % clean(rid))
        local = self.local_rows()
        rest = [r for r in rows if r["id"] != rid]
        self.save(rest)
        self.save_local({r["id"]: local[r["id"]] for r in rest if r["id"] in local})
        return {"id": rid, "forgotten": True}

    def rebind(self, rid, old_fp):
        rows = self.load()
        row = next((r for r in rows if r["id"] == rid), None)
        if row is None:
            raise Refused("no row with id %s" % clean(rid))
        local = self.local_rows()
        if local.get(rid) != self.row_digest(row) or row["constitution_root"] != self.root:
            raise Refused("row %s is not signed by this checkout; cannot rebind" % clean(rid))
        if row["fingerprint"] != old_fp:
            raise Refused("row %s fingerprint is not the expected old value; refusing" % clean(rid))
        fp = fingerprint(safe_rel(self.project, row["path"]), row["kind"], row.get("json_path"))
        if fp is None:
            raise Refused("item of row %s is absent or of another kind" % clean(rid))
        new = dict(row, fingerprint=fp)
        rest = [r for r in rows if r["id"] != rid] + [new]
        keep = {k: v for k, v in local.items() if k != rid}
        keep[rid] = self.row_digest(new)
        self.save(rest)
        self.save_local(keep)
        return {"id": rid, "fingerprint": fp}

    def status(self):
        rows, local = self.load(), self.local_rows()
        return {"rows": [dict(r, state=self.classify_row(r, local)) for r in sorted(rows, key=lambda r: r["id"])]}

    # -- inventory / adopt
    def _const_roots(self):
        roots = {self.root, os.path.abspath(self.root)}
        for sub in ("submodules/constitution", "constitution"):
            p = os.path.join(self.project, sub)
            if os.path.lexists(p):
                roots.add(os.path.abspath(p))
                roots.add(os.path.realpath(p))
        return roots

    def _points_into_constitution(self, link):
        try:
            tgt = os.path.abspath(os.path.join(os.path.dirname(link), os.readlink(link)))
        except OSError:
            return False
        real = os.path.realpath(tgt)
        for r in self._const_roots():
            for t in (tgt, real):
                if t == r or t.startswith(r + os.sep):
                    return True
        return False

    @staticmethod
    def _agent_for(rel):
        return AGENT_OF.get(rel.split("/")[0], "unknown")

    def inventory(self):
        cands = []
        for d in SCAN_DIRS:
            base = os.path.join(self.project, d)
            try:
                if stat.S_ISLNK(os.lstat(base).st_mode) or not stat.S_ISDIR(os.lstat(base).st_mode):
                    continue
                names = sorted(os.listdir(base))
            except OSError:
                continue
            for n in names:
                full, rel = os.path.join(base, n), d + "/" + n
                try:
                    st = os.lstat(full)
                except OSError:
                    continue
                if stat.S_ISLNK(st.st_mode):
                    if self._points_into_constitution(full):
                        cands.append({"path": rel, "kind": "symlink", "agent": self._agent_for(rel),
                                      "shape": "link-into-constitution"})
                elif stat.S_ISREG(st.st_mode) and st.st_size <= MAX_FILE:
                    try:
                        head = read_nofollow(full, MAX_FILE, rel)[:8192].decode("utf-8", "replace")
                    except Refused:
                        continue
                    if any(m in head for m in MARKERS):
                        cands.append({"path": rel, "kind": "file", "agent": self._agent_for(rel), "shape": "marker-file"})
        srel = ".claude/settings.json"
        sfull = os.path.join(self.project, srel)
        if os.path.lexists(sfull):
            try:
                groups = json_nav(load_json_file(sfull, srel), "hooks.UserPromptSubmit")
            except Refused:
                groups = None
            for i, g in enumerate(groups if isinstance(groups, list) else []):
                hooks = g.get("hooks") if isinstance(g, dict) else None
                if isinstance(hooks, list) and any(isinstance(h, dict) and isinstance(h.get("command"), str)
                                                   and h["command"].endswith(HOOK_SUFFIX) for h in hooks):
                    cands.append({"path": srel, "kind": "json-entry", "agent": "claude",
                                  "json_path": "hooks.UserPromptSubmit.%d" % i, "shape": "prompt-prefix-hook"})
        return {"candidates": cands}

    def adopt(self, mode, only):
        if mode not in ("none", "all-matching"):
            raise Refused("unknown adopt mode %r (use none or all-matching)" % clean(mode))
        cands = self.inventory()["candidates"]
        by_path = {}
        for c in cands:
            by_path.setdefault(c["path"], []).append(c)
        chosen = []
        for p in only:
            if p not in by_path:
                raise Refused("%s is not an adoptable candidate (not a known constitution shape)" % clean(p))
            chosen += by_path[p]
        if mode == "all-matching":
            chosen = cands
        done, skipped = [], []
        rows = {r["id"]: r for r in self.load()}
        taken = {(r["path"], r.get("json_path")) for r in rows.values()}
        for c in chosen:
            if (c["path"], c.get("json_path")) in taken:
                skipped.append(c["path"])
                continue
            rid = "adopted-" + hashlib.sha256((c["path"] + "|" + c.get("json_path", "")).encode()).hexdigest()[:12]
            self.record(rid, "adopt", c["agent"], c["path"], c["kind"], c.get("json_path"))
            done.append(c["path"])
        return {"adopted": len(done), "paths": done, "already_recorded": skipped}

    # -- backup / rollback
    def _bmac(self, key, manifest):
        body = {k: v for k, v in manifest.items() if k != "mac"}
        return hmac.new(key, b"wiring-backup\0" + canon(body), hashlib.sha256).hexdigest()

    def backup(self, rels):
        key = self.key(True)
        self.ensure_gitignore()
        base = os.path.join(self.project, BACKUP_DIR)
        if os.path.lexists(base) and not stat.S_ISDIR(os.lstat(base).st_mode):
            raise Refused("%s is not a real directory" % BACKUP_DIR)
        entries, seen = [], set()
        for rel in rels:
            full = safe_rel(self.project, rel)
            if rel in seen:
                continue
            seen.add(rel)
            try:
                st = os.lstat(full)
            except OSError:
                entries.append({"path": rel, "type": "absent"})
                continue
            if stat.S_ISLNK(st.st_mode):
                entries.append({"path": rel, "type": "symlink", "link": os.readlink(full)})
            elif stat.S_ISREG(st.st_mode):
                entries.append({"path": rel, "type": "file", "mode": stat.S_IMODE(st.st_mode)})
            else:
                raise Refused("%s is neither a file nor a symlink; refusing to back it up" % clean(rel))
        stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime(int(os.environ.get("SOURCE_DATE_EPOCH") or time.time())))
        os.makedirs(base, exist_ok=True)
        bgi = os.path.join(base, ".gitignore")          # F3: the backups hold copies of consumer files (settings may hold secrets)
        if not os.path.lexists(bgi):
            atomic_write(bgi, b"*\n")
        n, bdir = 0, None
        while True:
            cand = os.path.join(base, "%s-wiring%s" % (stamp, "" if n == 0 else "-%d" % n))
            try:
                os.mkdir(cand, 0o700)
                bdir = cand
                break
            except FileExistsError:
                n += 1
        files = {}
        for e in entries:
            if e["type"] == "file":
                data = read_nofollow(os.path.join(self.project, e["path"]), MAX_FILE, e["path"])
                e["sha256"] = hashlib.sha256(data).hexdigest()
                dst = os.path.join(bdir, "files", e["path"])
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                atomic_write(dst, data, 0o600)
        ledger = {}
        for name, src in (("wiring.json", self.led), ("wiring.local.json", self.loc)):
            if os.path.lexists(src):
                data = read_nofollow(src, MAX_JSON, name)
                os.makedirs(os.path.join(bdir, "ledger"), exist_ok=True)
                atomic_write(os.path.join(bdir, "ledger", name), data, 0o600)
                ledger[name] = hashlib.sha256(data).hexdigest()
            else:
                ledger[name] = None
        rows_at = sorted(r["id"] for r in self.load()) if os.path.lexists(self.led) else []
        manifest = {"schema": SCHEMA, "created": now_iso(), "project": self.project, "entries": entries,
                    "ledger": ledger, "rows_at_backup": rows_at}
        manifest["mac"] = self._bmac(key, manifest)
        atomic_write(os.path.join(bdir, "manifest.json"), (json.dumps(manifest, indent=1, sort_keys=True) + "\n").encode(), 0o600)
        return {"backup_dir": bdir, "entries": len(entries)}

    def _load_backup(self, bdir):
        bdir = os.path.realpath(bdir)
        mp = os.path.join(bdir, "manifest.json")
        if not os.path.isdir(bdir) or not os.path.lexists(mp):
            raise Refused("%s is not a backup directory (no manifest.json)" % clean(bdir))
        try:
            m = json.loads(read_nofollow(mp, MAX_JSON, "backup manifest").decode("utf-8"))
        except (UnicodeDecodeError, ValueError, RecursionError):
            raise Refused("backup manifest is not valid JSON")
        key = self.key(False)
        if key is None or not isinstance(m, dict) or not isinstance(m.get("mac"), str) \
                or not hmac.compare_digest(m["mac"], self._bmac(key, m)):  # RULE:W-backup-mac
            raise Refused("backup manifest signature is invalid (not made by this checkout, or edited)")
        if m.get("project") != self.project or m.get("schema") != SCHEMA:
            raise Refused("backup belongs to another project or schema")
        for e in m["entries"]:
            safe_rel(self.project, e["path"])
            if e["type"] == "file":
                blob = os.path.join(bdir, "files", e["path"])
                if hashlib.sha256(read_nofollow(blob, MAX_FILE, "backup blob")).hexdigest() != e["sha256"]:  # RULE:W-backup-blob
                    raise Refused("backup blob for %s does not match the manifest" % clean(e["path"]))
            elif e["type"] not in ("symlink", "absent"):
                raise Refused("backup manifest has an unknown entry type")
        for name, h in m["ledger"].items():
            if name not in ("wiring.json", "wiring.local.json"):
                raise Refused("backup manifest names an unknown ledger file")
            if h is not None and hashlib.sha256(read_nofollow(os.path.join(bdir, "ledger", name), MAX_JSON,
                                                                "backup ledger")).hexdigest() != h:
                raise Refused("backup ledger copy %s does not match the manifest" % name)
        return bdir, m

    def rollback(self, bdir):
        """Two phases. PREFLIGHT verifies the backup and plans every action (nothing is changed, any refusal here
        leaves the project byte-identical). APPLY then runs the plan. A created-later item is unlinked ONLY when its
        row classifies as ours (local HMAC signature + root binding + matching fingerprint); anything else, or any
        item whose state cannot be read (oversize, reserved path, unreadable), is left alone and reported."""
        bdir, m = self._load_backup(bdir)
        in_backup = {e["path"] for e in m["entries"]}
        backed = set(m["rows_at_backup"])
        restore = []
        for e in m["entries"]:
            full = safe_rel(self.project, e["path"])
            if os.path.lexists(full) and stat.S_ISDIR(os.lstat(full).st_mode):
                raise Refused("%s is now a directory; refusing to roll back over it" % clean(e["path"]))
            if e["type"] == "absent":
                continue
            if e["type"] == "file" and os.path.lexists(full) and stat.S_ISLNK(os.lstat(full).st_mode):
                raise Refused("%s is now a symlink; refusing to write through it (nothing was changed)" % clean(e["path"]))
            parent = os.path.dirname(full)
            probe = parent
            while not os.path.lexists(probe):
                probe = os.path.dirname(probe)
            if not stat.S_ISDIR(os.stat(probe).st_mode) or not os.access(probe, os.W_OK | os.X_OK):
                raise Refused("cannot restore %s: %s is not a writable directory" % (clean(e["path"]), clean(probe)))
            restore.append((e, full))
        report = {"restored": [], "unlinked": [], "left_alone": [], "rows_removed": []}
        unlink = []
        local = self.local_rows()
        for r in self.load() if os.path.lexists(self.led) else []:
            if r["id"] in backed:
                continue
            report["rows_removed"].append(r["id"])
            if r["path"] in in_backup:
                continue
            try:
                full = safe_rel(self.project, r["path"])
                if not os.path.lexists(full):
                    continue
                if r["kind"] not in ("symlink", "file"):
                    report["left_alone"].append({"path": r["path"], "reason": "json entry: never removed by rollback"})
                    continue
                if self.classify_row(r, local) != "ours":
                    report["left_alone"].append({"path": r["path"], "reason": "not ours (no local signature, another constitution root, or changed since it was recorded)"})
                    continue
                if not os.access(os.path.dirname(full), os.W_OK | os.X_OK):
                    report["left_alone"].append({"path": r["path"], "reason": "its directory is not writable"})
                    continue
                unlink.append((r["path"], full))
            except Refused as ex:
                report["left_alone"].append({"path": r["path"], "reason": "cannot be checked: %s" % clean(ex)})
        ledger_plan = []
        for name, dst in (("wiring.json", self.led), ("wiring.local.json", self.loc)):
            if m["ledger"][name] is not None:
                data = read_nofollow(os.path.join(bdir, "ledger", name), MAX_JSON, "backup ledger")
                if os.path.lexists(dst) and stat.S_ISLNK(os.lstat(dst).st_mode):
                    raise Refused("%s is a symlink; refusing to write through it (nothing was changed)" % clean(dst))
                self._need_dir(os.path.dirname(dst), True)
                ledger_plan.append((name, dst, data))
            else:
                ledger_plan.append((name, dst, None))
        blobs = {}
        for e, full in restore:
            if e["type"] == "file":
                blobs[e["path"]] = read_nofollow(os.path.join(bdir, "files", e["path"]), MAX_FILE, "backup blob")
        # ── apply: nothing below is expected to refuse ──
        for rel, full in unlink:
            os.unlink(full)
            report["unlinked"].append(rel)
        for e, full in restore:
            os.makedirs(os.path.dirname(full), exist_ok=True)
            if e["type"] == "symlink":
                tmp = full + ".tmp-%d-%s" % (os.getpid(), os.urandom(4).hex())
                os.symlink(e["link"], tmp)
                os.rename(tmp, full)
            else:
                atomic_write(full, blobs[e["path"]], e.get("mode", 0o644))
                os.chmod(full, e.get("mode", 0o644))
            report["restored"].append(e["path"])
        for name, dst, data in ledger_plan:
            if data is None:
                if os.path.lexists(dst) and not stat.S_ISDIR(os.lstat(dst).st_mode):
                    os.unlink(dst)
            else:
                atomic_write(dst, data, 0o600 if name.endswith("local.json") else 0o644)
        return report


# ── per-root reference file (D5) ─────────────────────────────────────────────
class Refs:
    def __init__(self, root, project):
        self.root = os.path.realpath(root)
        self.project = os.path.realpath(project)
        if "\t" in self.project or "\n" in self.project:
            raise Refused("project path contains a tab or newline")

    def _dir(self, create):
        ext = os.path.join(self.root, "extensions")
        if not os.path.isdir(ext) or stat.S_ISLNK(os.lstat(ext).st_mode):
            raise Refused("%s/extensions is not a real directory" % clean(self.root))
        d = os.path.join(ext, "_installed")
        if os.path.lexists(d):
            if not stat.S_ISDIR(os.lstat(d).st_mode):
                raise Refused("extensions/_installed is not a real directory")
        elif create:
            os.mkdir(d, 0o755)
        else:
            return None
        return d

    def _path(self, d, eid):
        if not ID_RE.match(eid or ""):
            raise Refused("extension id %r is not valid" % clean(eid))
        return os.path.join(d, eid + ".refs")

    def _read(self, p):
        if not os.path.lexists(p):
            return {}
        out = {}
        for ln in read_nofollow(p, MAX_JSON, "reference file").decode("utf-8", "surrogateescape").split("\n"):
            if not ln:
                continue
            f = ln.split("\t")
            if len(f) != 2 or not f[0].startswith("/") or not DIGEST_RE.match(f[1]):
                raise Refused("reference file has a corrupt line; refusing (nothing changed)")
            out[f[0]] = f[1]
        return out

    def _locked(self, create, eid, fn):
        d = self._dir(create)
        if d is None:
            return fn(None, {})
        p = self._path(d, eid)
        fd = os.open(d, os.O_RDONLY | os.O_DIRECTORY)
        try:
            fcntl.flock(fd, fcntl.LOCK_EX)  # RULE:W-refs-lock
            return fn(p, self._read(p))
        finally:
            os.close(fd)

    def _write(self, p, refs):
        if not refs:
            if os.path.lexists(p):
                os.unlink(p)
            return
        atomic_write(p, "".join("%s\t%s\n" % kv for kv in sorted(refs.items())).encode("utf-8", "surrogateescape"))

    def add(self, eid, digest):
        if not DIGEST_RE.match(digest or ""):
            raise Refused("--record-digest is required and must be a plain token")

        def fn(p, refs):
            refs[self.project] = digest
            self._write(p, refs)
            return {"id": eid, "count": len(refs)}
        return self._locked(True, eid, fn)

    def remove(self, eid):
        def fn(p, refs):
            if p is None:
                return {"id": eid, "count": 0}
            refs.pop(self.project, None)
            self._write(p, refs)
            return {"id": eid, "count": len(refs)}
        return self._locked(False, eid, fn)

    def count(self, eid):
        r = self._locked(False, eid, lambda p, refs: refs)
        return {"id": eid, "count": len(r)}

    def list(self, eid):
        r = self._locked(False, eid, lambda p, refs: refs)
        return {"id": eid, "refs": [{"project": k, "record_digest": v} for k, v in sorted(r.items())]}


# ── CLI ──────────────────────────────────────────────────────────────────────
def parse(argv):
    o = {"only": [], "path": []}
    pos = []
    i = 0
    multi = ("only", "path")
    while i < len(argv):
        a = argv[i]
        if a.startswith("--"):
            k = a[2:].replace("-", "_")
            if i + 1 >= len(argv):
                raise SystemExit(usage("option %s needs a value" % a))
            v = argv[i + 1]
            if k in multi:
                o[k].append(v)
            else:
                o[k] = v
            i += 2
        else:
            pos.append(a)
            i += 1
    return o, pos


def usage(msg):
    sys.stderr.write("wiring_ledger.py: %s\n(see the module docstring for the command list)\n" % msg)
    return 2


MUTATING = ("record", "forget", "rebind", "adopt", "backup", "rollback")


def main(argv):
    o, pos = parse(argv)
    if len(pos) < 1 or "project" not in o or "root" not in o:
        return usage("need --project, --root and a command")
    cmd = pos[0]
    try:
        out = run(cmd, o, pos[1:])
    except Refused as ex:
        sys.stderr.write("refused: %s\n" % clean(ex))
        return 3
    except Usage as ex:
        return usage(clean(ex))
    except (OSError, ValueError) as ex:                  # includes UnicodeError; never a traceback
        sys.stderr.write("refused: %s\n" % clean(getattr(ex, "strerror", None) or ex))
        return 3
    if out is None:
        return usage("unknown command %r" % clean(cmd))
    sys.stdout.write(json.dumps(out, indent=1, sort_keys=True) + "\n")
    return 0


def run(cmd, o, rest):
    if cmd == "refs":
        if len(rest) != 1 or rest[0] not in ("add", "remove", "count", "list"):
            raise Refused("refs needs one of add, remove, count, list")
        refs = Refs(o["root"], o["project"])
        eid = o.get("id", "")
        if rest[0] == "add":
            return refs.add(eid, o.get("record_digest", ""))
        return getattr(refs, rest[0])(eid)
    led = Ledger(o["project"], o["root"])
    lockfd = None
    if cmd in MUTATING:
        lockfd = os.open(led.project, os.O_RDONLY | os.O_DIRECTORY)
        fcntl.flock(lockfd, fcntl.LOCK_EX)
    try:
        if cmd in ("record", "classify") and not o["path"]:
            raise Usage("%s needs --path" % cmd)
        if cmd == "record":
            return led.record(o.get("id", ""), o.get("producer", ""), o.get("agent", ""), o["path"][-1],
                              o.get("kind", ""), o.get("json_path"), o.get("scope", "project"))
        if cmd == "classify":
            return led.classify(o["path"][-1])
        if cmd == "status":
            return led.status()
        if cmd == "forget":
            return led.forget(o.get("id", ""))
        if cmd == "rebind":
            return led.rebind(o.get("id", ""), o.get("old_fingerprint", ""))
        if cmd == "inventory":
            return led.inventory()
        if cmd == "adopt":
            return led.adopt(o.get("adopt", "none"), o["only"])
        if cmd == "backup":
            return led.backup(o["path"])
        if cmd == "rollback":
            return led.rollback(o.get("backup", ""))
        return None
    finally:
        if lockfd is not None:
            os.close(lockfd)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
