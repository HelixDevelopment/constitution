#!/usr/bin/env bash
# =============================================================================
# install_agent_label_defs.sh — install the §11.4.182 / §11.4.231(F) agent-type
#   label definitions T<N>-<branch>-<alias>-<model>-<effort> for the CURRENT
#   checkout into a consuming project's .claude/agents directory.
#
# Purpose : consumers regenerate their label agent types on every constitution
#   pull (wired from scripts/post_update_hook.sh, §11.4.164), idempotently, for
#   the alias of the session that runs it; other aliases' generated types in the
#   same checkout are kept (several aliases share one checkout); hand-made
#   definitions are never touched.
# Usage   : install_agent_label_defs.sh [--project-root <dir>] [--out-dir <dir>]
#             [--identity <N>:<branch>:<alias>] [--types m-e,...|--all-types]
#             [--check] [--dry-run] [--no-prune] [--no-git-exclude]
#           install_agent_label_defs.sh --remove-alias <alias> [--project-root D]
#             [--out-dir D] [--dry-run] [--no-git-exclude]
#             (retire an alias: removes ONLY that alias's GENERATED, unedited
#             files, exact alias match, with their export siblings; hand-made
#             and hand-edited files stay; refreshes the exclude block; needs no
#             live identity; any other flag is refused with exit 2)
# Inputs  : the LIVE identity of the checkout, from track_branch_label.sh run in
#   --project-root: track (trunk = T1, else /mnt/track<N>), branch (that
#   checkout's own HEAD) and Claude Toolkit alias (CLAUDE_CONFIG_DIR basename
#   .claude-<alias>). If ANY of the three is '?' the installer REFUSES (exit 6)
#   and writes, prunes and edits NOTHING — an identity is never guessed.
#   --identity supplies the triple explicitly instead (operator data, not a
#   guess; a '?' field is refused).
#   ONLY the current checkout is generated. Other tracks are generated by their
#   own worktree's hook run: another track's alias cannot be derived from this
#   session, and the multitrack config's mount/worktree_subdir data does not
#   reliably name the real checkout (measured on the reference host: config
#   `worktree_subdir: atmosphere`, real checkouts /mnt/trackN/atmosphere-tN), so
#   reading it would be a guess. The multitrack config is NOT an input: a
#   malformed or unreadable config can neither change nor prune anything.
#   Opt-out: AGENT_TYPE_LABEL_DEFS=off (or 0/false/no) in the environment, or a
#   file <out-dir>/.agent-label-defs-disabled — then nothing is written or pruned.
# Outputs : <out-dir>/ (default <project-root>/.claude/agents) gets the selected
#   definitions (default 4: sonnet-medium, sonnet-high, opus-high, opus-xhigh;
#   --all-types: 10) via gen_agent_label_defs.sh. Unless --no-git-exclude, a
#   managed block in the repository's .git/info/exclude (local, never committed)
#   lists EVERY generated file in the directory (any alias) and its
#   .html/.pdf/.docx export siblings, so host-derived definitions never ride
#   into a commit (`git add -A`).
# Exit codes: 0 ok (or opted out) · 1 drift (--check) · 2 usage · 3 some target
#   is HAND-MADE (left untouched) · 4 some target is a HAND-EDITED generated file
#   (left untouched) · 5 internal error · 6 identity unresolvable (nothing
#   touched) · 7 bash older than 4 · 8 flock (util-linux) missing while the
#   exclude file would be written (nothing written or pruned).
# Side-effects: writes generated files; prunes ONLY genuine generated files
#   that are v1 (round-1 format) or OWNED BY THE CURRENT ALIAS (alias read from
#   the file's description label) and not in the desired set (old branch,
#   track or type), together with their .html/.pdf/.docx export siblings.
#   Another alias's generated types are never pruned (several aliases share one
#   checkout); a hand-made file is never touched and a hand-edited superseded
#   generated file is kept with a WARN. --dry-run and --check write, prune and
#   edit nothing. --no-prune disables pruning.
# Deps    : bash >= 4, git, the sibling gen_agent_label_defs.sh /
#   track_branch_label.sh / agent_label_lib.sh.
# Cross-refs: §11.4.182 clause (8), §11.4.231 (F.5), §11.4.164, §11.4.177,
#   §11.4.201, gate CM-AGENT-TYPE-LABEL, docs/scripts/install_agent_label_defs.md.
# Classification: universal (§11.4.17).
# =============================================================================
set -uo pipefail
export LC_ALL=C

if [ "${AGENT_LABEL_BASH_MAJOR:-${BASH_VERSINFO[0]}}" -lt 4 ]; then
  echo "install_agent_label_defs: needs bash >= 4 (associative arrays); this is bash ${BASH_VERSION:-?} — nothing installed" >&2
  exit 7
fi

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
GEN="$HERE/gen_agent_label_defs.sh"
LABELER="$HERE/track_branch_label.sh"
# shellcheck source=agent_label_lib.sh disable=SC1091 # sibling library path resolved at runtime from the script directory
. "$HERE/agent_label_lib.sh" || { echo "install_agent_label_defs: cannot load agent_label_lib.sh" >&2; exit 5; }

project_root=""; out_dir=""; identity=""; type_flags=()
do_check=0; dry=0; prune=1; git_exclude=1; remove_alias=""; remove_set=0
die2() { echo "install_agent_label_defs: $*" >&2; exit 2; }
# need_val <argc> <option> <value>: one rule for every option taking a value (missing, empty or
# starting with '-' -> exit 2 naming the option; a path starting with '-' can be given as ./-name)
need_val() { if [ "$1" -lt 2 ] || ! al_value_ok "$3"; then die2 "$2 needs a value (got '${3-<missing>}'; a value may not be empty or start with '-')"; fi; }
seen_flags=()
while [ $# -gt 0 ]; do
  case "$1" in --*) seen_flags+=("$1") ;; esac
  case "$1" in
    --project-root) need_val $# --project-root "${2-}"; project_root="$2"; shift 2 ;;
    --out-dir)      need_val $# --out-dir "${2-}"; out_dir="$2"; shift 2 ;;
    --identity)     need_val $# --identity "${2-}"; identity="$2"; shift 2 ;;
    --types)        need_val $# --types "${2-}"; type_flags=(--types "$2"); shift 2 ;;
    --all-types)    type_flags=(--all-types); shift ;;
    --check)        do_check=1; shift ;;
    --dry-run)      dry=1; shift ;;
    --no-prune)     prune=0; shift ;;
    --no-git-exclude) git_exclude=0; shift ;;
    --remove-alias) need_val $# --remove-alias "${2-}"; remove_alias="$2"; remove_set=1; shift 2 ;;
    -h|--help)      awk 'NR >= 2 { print } NR > 2 && /^# =====/ { exit }' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *)              die2 "unknown argument '$1'" ;;
  esac
done
# --remove-alias is a separate mode (AL4-2): only the flags that make sense for retiring an alias are
# accepted with it; every other flag is refused BEFORE anything is read or touched, so e.g.
# --remove-alias --check can never delete (flag x mode matrix: docs/scripts/install_agent_label_defs.md).
if [ "$remove_set" -eq 1 ]; then
  for fl in "${seen_flags[@]}"; do
    case "$fl" in
      --remove-alias|--project-root|--out-dir|--dry-run|--no-git-exclude) ;;
      *) die2 "flag '$fl' is not accepted with --remove-alias (allowed: --project-root --out-dir --dry-run --no-git-exclude)" ;;
    esac
  done
fi
[ -n "$project_root" ] || project_root="${PROJECT_ROOT:-$(pwd -P)}"
al_path_ok "$project_root" || die2 "project root contains a control character; refused (nothing written)"
[ -d "$project_root" ] || die2 "project root '$project_root' is not a directory"
project_root="$(cd "$project_root" && pwd -P)"
al_path_ok "$project_root" || die2 "project root resolves to a path with a control character; refused (nothing written)"
[ -n "$out_dir" ] || out_dir="$project_root/.claude/agents"
# one entry rule for every path (AL5-2): no control character, neither as given nor resolved
al_path_ok "$out_dir" || die2 "out-dir contains a control character; refused (nothing written)"
if [ -d "$out_dir" ]; then al_path_ok "$(cd "$out_dir" && pwd -P)" || die2 "out-dir resolves to a path with a control character; refused (nothing written)"; fi
# the shared exclude file is only ever rewritten under flock (util-linux); without it nothing is
# written at all (exit 8). --no-git-exclude, --check and --dry-run need no lock.
FLOCK="${AGENT_LABEL_FLOCK_BIN:-flock}"
need_lock=0
if [ "$git_exclude" -eq 1 ] && [ "$dry" -eq 0 ]; then
  if [ "$remove_set" -eq 1 ] || [ "$do_check" -eq 0 ]; then need_lock=1; fi
fi
if [ "$need_lock" -eq 1 ] && ! command -v "$FLOCK" >/dev/null 2>&1; then
  echo "install_agent_label_defs: flock (util-linux) not found; the shared .git/info/exclude is only rewritten under flock — nothing written or pruned. Install util-linux, or pass --no-git-exclude." >&2
  exit 8
fi
[ -r "$GEN" ] || { echo "install_agent_label_defs: generator missing: $GEN" >&2; exit 5; }

# --- exclude block (structural rounds 5-6, AL4-1/AL5-1/AL5-2). A linked worktree shares ONE
# info/exclude with its main worktree, so the block key is the ABSOLUTE physical out-dir. Grammar (one
# rule for every block state): a managed begin line pairs ONLY with the first matching end line that
# comes BEFORE the next managed begin line of ANY key; a paired block of our key (or of a legacy
# round-3/4 key of the same <rel>) is replaced, a begin with no such end is a LONE begin and only that
# marker line is dropped (the lines after it are user lines and are kept), an end of our key that
# closes nothing is an ORPHAN marker line and is dropped. Keys are compared byte-exactly (they reach
# awk through ENVIRON, never -v, which would interpret backslashes) and nothing is stripped from a
# key; paths with any control character are refused at entry, so no key can contain CR or LF. A
# trailing CR on a FILE line (a CRLF-converted exclude) is ignored, which can only make our own
# rewritten marker match. A v2 block whose directory no longer exists and lies under no
# `git worktree list` worktree is collected. The read-modify-write of the shared file runs under
# flock (required; exit 8 without it) and is replaced atomically (temp file + rename in the same
# directory); a killed holder releases the lock with its death and its temp file is removed.
gi_escape() { # gitignore-escape a path: backslash before \ * ? [ and before a trailing space
  local p="$1"
  p="${p//\\/\\\\}"; p="${p//\*/\\*}"; p="${p//\?/\\?}"; p="${p//\[/\\[}"
  case "$p" in *' ') p="${p% }\\ " ;; esac
  printf '%s' "$p"
}
# shellcheck disable=SC2016 # the awk program is single-quoted on purpose; its $0/$i are awk fields
EXCL_AWK='
  function cr(s) { sub(/\r$/, "", s); return s }
  function lend(b,   mid) {            # the end line a begin line expects, or "" (not ours)
    if (b == ENVIRON["B"]) return ENVIRON["E"]
    if (index(b, V2) == 1 && (substr(b, length(V2) + 1) in STALE)) return "# <<< agent-label-defs v2 " substr(b, length(V2) + 1)
    if (index(b, LP) == 1 && length(b) > length(LP) + length(LS) - 1 && substr(b, length(b) - length(LS) + 1) == LS) {
      mid = substr(b, length(LP) + 1, length(b) - length(LP) - length(LS))
      if (mid == "") return "# <<< agent-label-defs " ENVIRON["R"]
      if (mid ~ /^T[0-9]+ $/) return "# <<< agent-label-defs " ENVIRON["R"] " " substr(mid, 1, length(mid) - 1)
    }
    return ""
  }
  { L[NR] = $0; C[NR] = cr($0) }
  END {
    V2 = "# >>> agent-label-defs v2 "
    n = split(ENVIRON["S"], sk, "\n"); for (q = 1; q <= n; q++) if (sk[q] != "") STALE[sk[q]] = 1
    LP = "# >>> agent-label-defs " ENVIRON["R"] " "
    LS = "(managed by install_agent_label_defs.sh; host-derived agent types, do not commit)"
    for (i = 1; i <= NR; i++) {
      if (drop[i]) continue
      want = lend(C[i]); if (want == "") continue
      for (j = i + 1; j <= NR; j++) {
        if (index(C[j], "# >>> agent-label-defs ") == 1) { j = NR + 1; break }
        if (C[j] == want) break
      }
      if (j <= NR) { for (k = i; k <= j; k++) drop[k] = 1 } else drop[i] = 1
    }
    for (i = 1; i <= NR; i++) if (!drop[i] && C[i] == ENVIRON["E"]) drop[i] = 1
    for (i = 1; i <= NR; i++) if (!drop[i]) print L[i]
  }'
excl_lock_take() { # dir -> 0 when fd 8 holds an exclusive flock on <dir>/.agent-label-defs.lock
  local d="$1"
  exec 8>>"$d/.agent-label-defs.lock" || return 1
  "$FLOCK" -w "${AGENT_LABEL_LOCK_WAIT:-30}" 8 || { exec 8>&-; return 1; }
  return 0
}
excl_lock_drop() { exec 8>&-; }   # closing the fd releases the lock (the kernel also does on death)
update_exclude() {
  local top excl rel relq od tmp f b base x begin end note d rc=0 stale="" k w live
  top="$(git -C "$project_root" rev-parse --show-toplevel 2>/dev/null)" || return 0
  top="$(cd "$top" && pwd -P)"
  [ -d "$out_dir" ] || return 0
  od="$(cd "$out_dir" && pwd -P)"
  al_path_ok "$od" || { echo "WARN     out-dir path contains a control character; exclude block not written" >&2; return 0; }
  case "$od" in "$top"/*) rel="${od#"$top"/}" ;; *) return 0 ;; esac
  excl="$(git -C "$project_root" rev-parse --git-path info/exclude 2>/dev/null)" || return 0
  case "$excl" in /*) ;; *) excl="$project_root/$excl" ;; esac
  d="$(dirname "$excl")"
  mkdir -p "$d" || return 0
  begin="# >>> agent-label-defs v2 ${od}"; end="# <<< agent-label-defs v2 ${od}"
  note="# managed by install_agent_label_defs.sh; host-derived agent types, do not commit"
  relq="$(gi_escape "$rel")"
  excl_lock_take "$d" || { echo "WARN     could not lock $excl (another install holds it); exclude block not written" >&2; return 0; }
  # stale keys: a v2 block whose directory no longer exists AND lies under no worktree of this
  # repository (a removed linked worktree, a moved checkout) is collected; any doubt keeps it.
  if [ -f "$excl" ]; then
    while IFS= read -r k; do
      k="${k%$'\r'}"; k="${k#"# >>> agent-label-defs v2 "}"
      case "$k" in /*) ;; *) continue ;; esac
      [ -e "$k" ] && continue
      live=0
      while IFS= read -r w; do
        case "$w" in "worktree "*) w="${w#worktree }"; case "$k" in "$w"|"$w"/*) live=1 ;; esac ;; esac
      done < <(git -C "$project_root" worktree list --porcelain 2>/dev/null)
      [ "$live" -eq 0 ] && stale="$stale$k"$'\n'
    done < <(grep -a '^# >>> agent-label-defs v2 /' "$excl")
  fi
  rm -f -- "$excl".tmp.*   # under the lock any temp file is a killed holder's leftover
  tmp="$excl.tmp.$$"
  {
    : >"$tmp" &&
    if [ -f "$excl" ]; then B="$begin" E="$end" R="$rel" S="$stale" awk "$EXCL_AWK" "$excl" >>"$tmp"; fi &&
    {
      echo "$begin"
      echo "$note"
      for f in "$out_dir"/T[0-9]*-*.md; do
        [ -e "$f" ] || continue
        b="${f##*/}"
        [[ "$b" =~ ^T[0-9]+-[a-z0-9-]+-(sonnet|opus)-(low|medium|high|xhigh|max)\.md$ ]] || continue
        case "$(bash "$GEN" --classify "$f")" in genuine|edited) ;; *) continue ;; esac
        base="${b%.md}"
        printf '/%s/%s\n' "$relq" "$b"
        for x in html pdf docx; do printf '/%s/%s.%s\n' "$relq" "$base" "$x"; done
      done | LC_ALL=C sort
      echo "$end"
    } >>"$tmp" &&
    { [ -z "${AGENT_LABEL_EXCL_DELAY:-}" ] || sleep "$AGENT_LABEL_EXCL_DELAY"; } &&   # test hook: widen the read->rename window
    mv -f "$tmp" "$excl"
  } || { rm -f "$tmp"; echo "WARN     could not update $excl" >&2; rc=1; }
  excl_lock_drop
  return "$rc"
}
prune_one() { # file: the .md and its .html/.pdf/.docx export siblings
  local f="$1" base x
  base="${f%.md}"
  rm -f -- "$f" || return 1
  for x in html pdf docx; do rm -f -- "$base.$x"; done
  return 0
}

# --- retire an alias (explicit operator action; no live identity needed) -------------------------
if [ "$remove_set" -eq 1 ]; then
  case "$remove_alias" in '?'|'') die2 "--remove-alias needs a concrete alias (got '${remove_alias}')" ;; esac
  ra="$(al_sanitise "$remove_alias")"; [ -n "$ra" ] || die2 "--remove-alias '${remove_alias}' sanitises to an empty name"
  nrem=0
  if [ -d "$out_dir" ]; then
    shopt -s nullglob
    for f in "$out_dir"/T[0-9]*-*.md; do
      b="${f##*/}"
      [[ "$b" =~ ^T[0-9]+-[a-z0-9-]+-(sonnet|opus)-(low|medium|high|xhigh|max)\.md$ ]] || continue
      [ "$(bash "$GEN" --classify "$f")" = genuine ] || continue
      [ "$(al_sanitise "$(bash "$GEN" --owner-alias "$f")")" = "$ra" ] || continue
      if [ "$dry" -eq 1 ]; then echo "PLAN     $b (remove: alias ${remove_alias})"
      else prune_one "$f" && echo "REMOVED  $b (alias ${remove_alias}) + export siblings"; fi
      nrem=$((nrem+1))
    done
    shopt -u nullglob
  fi
  if [ "$git_exclude" -eq 1 ] && [ "$dry" -eq 0 ]; then update_exclude; fi
  echo "install_agent_label_defs: --remove-alias ${remove_alias}: ${nrem} generated file(s) $([ "$dry" -eq 1 ] && echo planned || echo removed); hand-made files untouched"
  exit 0
fi

# --- opt-out (consumer data) ---------------------------------------------------------------
case "${AGENT_TYPE_LABEL_DEFS:-}" in
  off|0|false|no) echo "NOTE     agent-type label definitions disabled (AGENT_TYPE_LABEL_DEFS=${AGENT_TYPE_LABEL_DEFS}); nothing written or pruned"; exit 0 ;;
esac
if [ -e "$out_dir/.agent-label-defs-disabled" ]; then
  echo "NOTE     agent-type label definitions disabled ($out_dir/.agent-label-defs-disabled); nothing written or pruned"; exit 0
fi

# --- 1. identity: explicit, or the live labeler in the project root -------------------------
trk=""; br=""; al=""; src=""
if [ -n "$identity" ]; then
  trk="${identity%%:*}"; al="${identity##*:}"; br="${identity#*:}"; br="${br%:*}"
  case "$identity" in *:*:*) ;; *) die2 "--identity must be <N>:<branch>:<alias>" ;; esac
  case "$trk$br$al" in *'?'*) die2 "--identity '$identity' has an unknown ('?') field" ;; esac
  src="--identity"
else
  [ -r "$LABELER" ] || { echo "install_agent_label_defs: labeler missing: $LABELER" >&2; exit 5; }
  lab="$(cd "$project_root" && bash "$LABELER" 2>/dev/null || true)"
  inner="${lab#(}"; inner="${inner%)}"
  first="${inner%%' - '*}"; rest="${inner#*' - '}"
  al="${rest%%' - '*}"
  trk="${first#T}"; trk="${trk%%/*}"; br="${first#*/}"
  [ "$lab" != "$inner" ] || { trk='?'; br='?'; al='?'; }
  src="track_branch_label.sh ($lab)"
fi
if [ -z "$trk" ] || [ -z "$br" ] || [ -z "$al" ] || [ "$trk" = '?' ] || [ "$br" = '?' ] || [ "$al" = '?' ]; then
  echo "REFUSE   identity unresolvable from ${src}: track='${trk:-}' branch='${br:-}' alias='${al:-}'."
  echo "         Nothing written, pruned or edited (an identity is never guessed, §11.4.6)."
  echo "         Run from the session bound to this checkout (CLAUDE_CONFIG_DIR=.../.claude-<alias>), or pass --identity <N>:<branch>:<alias>."
  exit 6
fi
trk="$(printf '%s' "$trk" | sed 's/^0*\([0-9]\)/\1/')"

# --- 2. desired names from the generator itself (single source, AL-6) ----------------------
names_out="$(bash "$GEN" --track "$trk" --branch "$br" --alias "$al" --out-dir "$out_dir" ${type_flags[@]+"${type_flags[@]}"} --print-names 2>&1)"; r=$?
if [ "$r" -ne 0 ]; then printf '%s\n' "$names_out" >&2; exit "$r"; fi
declare -A DESIRED=()
while IFS= read -r n; do [ -n "$n" ] && DESIRED["$n"]=1; done <<<"$names_out"

# --- 3. generate -------------------------------------------------------------------------------
gen_flags=(${type_flags[@]+"${type_flags[@]}"})
[ "$do_check" -eq 1 ] && gen_flags+=(--check)
[ "$dry" -eq 1 ] && gen_flags+=(--dry-run)
out="$(bash "$GEN" --track "$trk" --branch "$br" --alias "$al" --out-dir "$out_dir" ${gen_flags[@]+"${gen_flags[@]}"})"; r=$?
printf '%s\n' "$out"
any1=0; any3=0; any4=0; any5=0
case "$r" in 0) ;; 1) any1=1 ;; 3) any3=1 ;; 4) any4=1 ;; *) any5=1 ;; esac
nw="$(printf '%s\n' "$out" | sed -n 's/.*written=\([0-9][0-9]*\) unchanged=.*/\1/p' | tail -n1)"
nu="$(printf '%s\n' "$out" | sed -n 's/.*unchanged=\([0-9][0-9]*\).*/\1/p' | tail -n1)"

# --- 4. prune ------------------------------------------------------------------------------------
# Topology (probe 2026-10-15): several Claude Toolkit aliases share ONE checkout (on the reference
# host the single T1 checkout holds claude1, claude4 and claude5 types side by side; the conductor
# stays on it and every trunk session is T1). The installer cannot tell a retired alias from a live
# session of another alias, so OWNERSHIP decides: a generated v2 file belongs to the alias in its
# description label (--owner-alias). Pruned: v1 files (round-1 format, no owner) and THIS alias's
# generated files that are no longer desired (old branch, track or type). Another alias's files are
# NEVER pruned — the operator removes a retired alias's types explicitly. A pruned file's
# .html/.pdf/.docx export siblings go with it.
npruned=0; nkept_other=0
my_alias="$(al_sanitise "$al")"
if [ -d "$out_dir" ]; then
  shopt -s nullglob
  for f in "$out_dir"/T[0-9]*-*.md; do
    b="${f##*/}"
    [[ "$b" =~ ^T[0-9]+-[a-z0-9-]+-(sonnet|opus)-(low|medium|high|xhigh|max)\.md$ ]] || continue
    [ -n "${DESIRED[$b]:-}" ] && continue
    cl="$(bash "$GEN" --classify "$f")"
    case "$cl" in genuine|edited) ;; *) continue ;; esac
    if grep -q '^<!-- generated-by: gen_agent_label_defs\.sh v1 ' "$f"; then
      owner=""
    else
      owner="$(bash "$GEN" --owner-alias "$f")"
      if [ "$(al_sanitise "$owner")" != "$my_alias" ]; then
        nkept_other=$((nkept_other+1)); continue      # another alias's file: never ours to delete
      fi
    fi
    if [ "$cl" = edited ]; then echo "WARN     $b is a superseded generated file that was hand-edited; left untouched" >&2; continue; fi
    if [ "$do_check" -eq 1 ]; then echo "DRIFT    $b (superseded generated file of alias ${owner:-<v1>})"; any1=1
    elif [ "$prune" -eq 0 ]; then echo "KEEP     $b (superseded generated file; --no-prune)"
    elif [ "$dry" -eq 1 ]; then echo "PLAN     $b (prune superseded generated file + export siblings)"; npruned=$((npruned+1))
    else prune_one "$f" && { echo "PRUNED   $b (superseded generated file + export siblings)"; npruned=$((npruned+1)); }; fi
  done
  shopt -u nullglob
fi
[ "$nkept_other" -gt 0 ] && echo "NOTE     kept ${nkept_other} generated type(s) of other aliases (never pruned here; remove a retired alias's types explicitly)"

# --- 5. keep host-derived definitions out of `git status` (.git/info/exclude, local only) --------
if [ "$git_exclude" -eq 1 ] && [ "$do_check" -eq 0 ] && [ "$dry" -eq 0 ]; then update_exclude; fi

if [ "$do_check" -eq 0 ] && [ "$dry" -eq 0 ] && { [ "${nw:-0}" -gt 0 ] || [ "$npruned" -gt 0 ]; }; then
  echo "NOTE     agent types changed: a running session sees them only after its agent registry refreshes (no guaranteed time; measured 2 min to never) — restart the session before dispatching them."
fi
echo "install_agent_label_defs: T${trk}/${br} alias ${al}: written=${nw:-0} unchanged=${nu:-0} pruned=${npruned}$([ "$dry" -eq 1 ] && echo ' (dry-run)')$([ "$do_check" -eq 1 ] && echo ' (check)')"
if   [ "$any5" -eq 1 ]; then exit 5
elif [ "$any3" -eq 1 ]; then exit 3
elif [ "$any4" -eq 1 ]; then exit 4
elif [ "$any1" -eq 1 ]; then exit 1
fi
exit 0
