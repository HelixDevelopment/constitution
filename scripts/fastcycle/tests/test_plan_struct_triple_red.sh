#!/bin/bash
# Purpose : T179's own remaining gap (SpecKit-004 "fast-dev-cycles", tracked
#           separately as ATM-1109, Task/Medium/Queued) -- RED/regression
#           test for the `triple` subcommand of `plan_struct_check.py`,
#           implementing CT-5 (plan.md's own Constitution-Check table,
#           Post-Design Principle IV): "Every oracle, analyzer, judge and
#           guard ships the self-validation triple". Per plan.md line 128
#           and T179's own tasks.md line: "tasks.md adds the negative
#           controls in T052 (T-C02), T125 (T-B04), T126 (T-B05), T091
#           (T-D06); the box stays unchecked until T179's triple check
