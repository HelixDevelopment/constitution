# --- hr_bad_live_session_dir: real backup + marker + confirmation, but a live
#     process has this target as its cwd -- must be refused regardless.
T4="$WORK/t4"; mk_target "$T4" "content-four"
B4="$WORK/backup4"; cp -a "$T4" "$B4"
ADDR4=$(python3 - "$B4" <<'PYEOF'
import hashlib, os, sys
