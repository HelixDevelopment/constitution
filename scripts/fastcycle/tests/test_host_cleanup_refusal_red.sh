# T143 RED test (SpecKit-004 "fast-dev-cycles", User Story 6, plan task T-F03,
# contract host-resource-attribution.md HR-004/HR-003) for
# `host/host_report.py cleanup`.
#
# Fixtures (contract's own RED-fixture table, host-resource-attribution.md):
#   hr_bad_delete_no_backup       -- no --backup-marker at all: refused, untouched
#   hr_bad_backup_hash_mismatch   -- marker's recorded content address wrong: refused
#   hr_bad_no_confirmation        -- no --confirmation: refused
#   hr_bad_live_session_dir       -- target held by a live pid (real /proc cwd): refused
#   hr_good_confirmed_backed_up   -- real backup, real confirmation, --apply:
#                                     executes; the backup itself re-verifies afterwards
#   Paired mutation (this file also proves the SHAPE the mutation must catch,
#     T146 exercises the flip itself): skipping HR-004(a) re-verification would
#     let hr_bad_backup_hash_mismatch execute -- this test's mismatch fixture
#     is therefore written to be a REAL, non-trivial hash mismatch (a
#     genuinely different backup on disk, not merely a wrong string), so a
#     GREEN implementation cannot pass by accident.
#
# Producer != Verifier: every fixture backup/marker/confirmation file below is
# built by this test script directly (its own content-address function,
# reimplemented independently rather than imported from the tool under test,
# §11.4.245 derived oracle) -- never generated by calling `cleanup` itself.

set -u
HERE=$(cd "$(dirname "$0")" && pwd)
FC_ROOT=$(cd "$HERE/.." && pwd)
TOOL="$FC_ROOT/host/host_report.py"
FAIL=0; PASS=0
ok()  { PASS=$((PASS+1)); echo "PASS: $1"; }
bad() { FAIL=$((FAIL+1)); echo "FAIL: $1"; }

if [ ! -f "$TOOL" ]; then
  echo "RED: host_report.py absent at $TOOL"
  bad "host_report.py exists"
  echo "SUMMARY pass=$PASS fail=$FAIL"; exit 1
fi

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

sha256_file() { python3 -c "import hashlib,sys; print(hashlib.sha256(open(sys.argv[1],'rb').read()).hexdigest())" "$1"; }

# content_addr_of <dir> -- Producer != Verifier (§11.4.245): a directory
# content-address function independently re-implemented here (never
# imported from host_report.py), matching the same manifest-hash shape
# T3/T4/T5's inline heredocs already used before this helper was factored
# out of their duplication.
content_addr_of() {
  python3 - "$1" <<'PYEOF'
import hashlib, os, sys
root = sys.argv[1]
entries = []
for dirpath, _dirs, files in os.walk(root):
    for f in sorted(files):
        p = os.path.join(dirpath, f)
        rel = os.path.relpath(p, root)
        h = hashlib.sha256(open(p, "rb").read()).hexdigest()
        entries.append((rel, h))
entries.sort()
manifest = "\n".join("%s\0%s" % e for e in entries)
print(hashlib.sha256(manifest.encode()).hexdigest())
PYEOF
}

# The fixed, well-known content-address of an EMPTY directory: sha256 of an
# EMPTY manifest string -- identical for ANY empty directory anywhere,
# regardless of what it is or where it lives. This is exactly the B1(c)
# vulnerability: a marker can record THIS value and point backup_path at
# ANY unrelated empty directory, and a self-consistency-only check
# (recorded == content_address(backup_path)) is satisfied trivially.
EMPTY_DIR_ADDR="e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"

mk_target() {  # mk_target <dir> <content>
  mkdir -p "$1"
  printf '%s' "$2" > "$1/marker.txt"
}

# --- hr_bad_delete_no_backup ---
T1="$WORK/t1"; mk_target "$T1" "content-one"
OUT="$WORK/out1.json"
python3 "$TOOL" cleanup --target "$T1" --backup-marker "$WORK/nope-marker.json" \
  --confirmation "$WORK/nope-confirm.json" --out "$OUT" --apply >"$WORK/o1.log" 2>&1
rc=$?
if [ "$rc" -eq 1 ] && [ -f "$T1/marker.txt" ] && [ "$(cat "$T1/marker.txt")" = "content-one" ]; then
  ok "hr_bad_delete_no_backup: refused (exit 1), target byte-identical"
else
  bad "hr_bad_delete_no_backup: expected refused+untouched, got rc=$rc target-present=$([ -f "$T1/marker.txt" ] && echo yes || echo no)"
fi

# --- hr_bad_delete_no_backup, ISOLATED: confirmation is CORRECT and present;
#     ONLY the backup marker is missing. This isolates HR-004(a) from
#     HR-004(b) (T146 finding: the combined-missing fixture above does not
#     by itself prove the marker-check is load-bearing, since disabling it
#     alone still leaves the confirmation-check refusing -- a mutation that
#     drops JUST the marker check silently passed the combined fixture).
