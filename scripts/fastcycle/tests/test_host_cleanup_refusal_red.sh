fi

# --- hr_bad_no_confirmation: real backup + correct marker hash, no confirmation ---
T3="$WORK/t3"; mk_target "$T3" "content-three"
B3="$WORK/backup3"; cp -a "$T3" "$B3"
python3 - "$B3" > "$WORK/addr3.txt" <<'PYEOF'
