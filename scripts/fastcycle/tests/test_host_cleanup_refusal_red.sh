  --confirmation "$CONFIRM1B" --out "$WORK/out1b.json" --apply >"$WORK/o1b.log" 2>&1
rc=$?
if [ "$rc" -eq 1 ] && [ -f "$T1B/marker.txt" ]; then
  ok "hr_bad_delete_no_backup (isolated, confirmation present+correct): refused (exit 1), target untouched"
else
  bad "hr_bad_delete_no_backup (isolated): expected refused, got rc=$rc target-present=$([ -f "$T1B/marker.txt" ] && echo yes || echo no)"
fi

# --- hr_bad_backup_hash_mismatch: real backup exists, marker records the WRONG hash ---
T2="$WORK/t2"; mk_target "$T2" "content-two"
B2="$WORK/backup2"; mk_target "$B2" "DIFFERENT-content-entirely"
