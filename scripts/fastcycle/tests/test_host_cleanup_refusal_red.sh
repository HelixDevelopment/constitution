CONFIRM2="$WORK/confirm2.json"
cat > "$CONFIRM2" <<JSON
{"target": "$T2", "operator": "test", "confirmed_at": "2026-09-30T00:00:00Z"}
JSON
python3 "$TOOL" cleanup --target "$T2" --backup-marker "$MARKER2" --confirmation "$CONFIRM2" \
  --out "$WORK/out2.json" --apply >"$WORK/o2.log" 2>&1
