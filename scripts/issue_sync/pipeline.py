"""The issues-sync FACADE (anchor 11.4.300; operator decision 2026-11-25): ONE entry point for the whole bidirectional pipeline, bound to the
Docs Chain context `issues-sync`. Subcommands: plan, apply (outbound), pull (inbound proposals), reconcile (DB vs tracker), verify, run
(the whole chain), init-context, stage (internal: a Docs Chain exec transform).
Policy: the workable-items DB wins; inbound is reviewable PROPOSAL files; a conflicting tracker edit is reported and is never applied or overwritten
until its text is preserved as a proposal. Dry-run is the default everywhere. Three-valued exit: 0 ok, 1 drift/conflict/refused, 2 cannot determine
(never a pass). Tokens are read by variable NAME elsewhere (credentials.py) and are never printed here."""
import argparse
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile

from . import cli, config as cfgmod, credentials, inbound

SUBCOMMANDS = ("plan", "apply", "pull", "reconcile", "verify", "run", "init-context", "stage")
CONTEXT_NAME = "issues-sync"
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
TEMPLATE = os.path.join(ROOT, "templates", "docs_chain", "issues-sync.yaml")
EXEC_MARK = "--docs-chain-exec"


def split_exec_argv(argv):
    """Docs Chain calls an exec transform as `<in...> <out> <args...>`; the context puts EXEC_MARK first in args. -> (ins, out, rest) or None."""
    if EXEC_MARK not in argv:
        return None
    k = argv.index(EXEC_MARK)
    paths = argv[:k]
    if not paths:
        return None
    return paths[:-1], paths[-1], argv[k + 1:]


def find_docs_chain(env):
    b = env.get("DOCS_CHAIN_BIN")
    if b and os.access(b, os.X_OK):
        return b
    return shutil.which("docs_chain")


def token_status(token_vars):
    """Names only: 'NAME: found|absent|invalid'. The value is never read into this string."""
    st, name, _ = credentials.resolve(token_vars)       # the value slot is discarded here on purpose
    return "%s: %s" % (name or "|".join(token_vars), st)


def _strip(args, flags):
    return [x for x in args if x not in flags]


def _capture(argv, **kw):
    buf = io.StringIO()
    rc = cli.run(argv, out=buf, **kw)
    return rc, buf.getvalue()


def guard_conflicts(rest, **kw):
    """-> list of (leg, item, number) tracker edits whose text is NOT yet preserved as a proposal. Read-only."""
    rc, text = _capture(["reconcile"] + _strip(rest, ("--apply", "--write")), **kw)
    bad = []
    for line in text.splitlines():
        try:
            rep = json.loads(line)
        except ValueError:
            continue
        for r in (rep.get("records") or []) if isinstance(rep, dict) else []:
            if r.get("class") == "tracker-edited" and not r.get("captured"):
                bad.append((rep.get("leg"), r.get("item"), r.get("number")))
    return bad


def cmd_apply(rest, out, kw):
    if "--apply" in rest:
        bad = guard_conflicts(rest, **kw)
        if bad:
            print("apply refused: %d tracker edit(s) would be overwritten (the database wins) before their text is preserved: %s. "
                  "Run `pull --write` first (it saves each tracker version as a reviewable proposal), then apply again." %
                  (len(bad), "; ".join("%s #%s item %s" % b for b in bad)), file=out)
            return 1
    return cli.run(["apply"] + rest, out=out, **kw)


def cmd_init_context(args, out):
    ap = argparse.ArgumentParser(prog="init-context")
    ap.add_argument("--root", default=".")
    ap.add_argument("--owner-repo", help="HOST/OWNER/REPO substituted for the placeholder in the template (owner and the single default target)")
    ap.add_argument("--write", action="store_true", help="write .docs_chain/contexts/issues-sync.yaml (default: print what would be written)")
    a = ap.parse_args(args)
    text = open(TEMPLATE).read()
    if a.owner_repo:
        text = text.replace("HOST/OWNER/REPO", a.owner_repo)
    dest = os.path.join(a.root, ".docs_chain", "contexts", CONTEXT_NAME + ".yaml")
    if not a.write:
        print("dry-run: would write %s (%d bytes); add --write" % (dest, len(text)), file=out)
        return 0
    if os.path.exists(dest):
        print("refused: %s exists; edit it by hand (never overwritten)" % dest, file=out)
        return 1
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "x") as f:
        f.write(text)
    print("wrote %s" % dest, file=out)
    return 0


def _md(title, body):
    return "# %s\n\nGenerated by scripts/issues_sync_pipeline.sh (a Docs Chain stage); do not edit.\n\n%s\n" % (title, body)


def cmd_stage(rest, out_path, out, kw):
    """A Docs Chain exec transform. Writes ONLY the staged output file. Tool failure is exit 3-class (rc 1 here); a three-valued verdict of the
    tracker side is recorded IN the report and the stage still exits 0, so one unreachable tracker never rolls the whole chain back; `run` ends with the real verdict."""
    if not rest:
        print("stage: name required", file=sys.stderr)
        return 2
    name, opts = rest[0], rest[1:]
    if name in ("db-to-issues-md", "db-to-fixed-md"):
        ap = argparse.ArgumentParser(prog="stage")
        ap.add_argument("--db", default="docs/workable_items.db")
        ap.add_argument("--workable-items-bin", default=os.environ.get("WORKABLE_ITEMS_BIN") or os.path.join(ROOT, "scripts", "workable-items", "bin", "workable-items-linux"))
        a, _ = ap.parse_known_args(opts)
        d = tempfile.mkdtemp()
        try:
            p = subprocess.run([a.workable_items_bin, "sync", "db-to-md", "--db", a.db, "--out-issues", os.path.join(d, "I.md"), "--out-fixed", os.path.join(d, "F.md")],
                               capture_output=True, text=True)
            src = os.path.join(d, "I.md" if name == "db-to-issues-md" else "F.md")
            if p.returncode != 0 or not os.path.isfile(src):
                print("stage %s: workable-items failed (rc %s)" % (name, p.returncode), file=sys.stderr)
                return 1
            shutil.copyfile(src, out_path)
        finally:
            shutil.rmtree(d, ignore_errors=True)
        return 0
    sub = {"outbound": "plan", "inbound": "pull", "verify": "verify"}.get(name)
    if sub is None:
        print("stage: unknown stage %s" % name, file=sys.stderr)
        return 2
    if name == "outbound" and "--apply" in opts:
        sub = "apply"
    rc, text = _capture([sub] + opts, **kw) if sub != "apply" else (cmd_apply_capture(opts, kw))
    body = "Verdict: %s\n\n```text\n%s\n```" % ({0: "OK (0)", 1: "DRIFT (1)", 2: "UNDETERMINED (2: never a pass)"}.get(rc, "ERROR (%s)" % rc), text.rstrip())
    if name == "verify":
        rc2, t2 = _capture(["reconcile"] + _strip(opts, ("--apply", "--write")), **kw)
        body += "\n\nReconcile (%s):\n\n```text\n%s\n```" % ({0: "0", 1: "1", 2: "2"}.get(rc2, str(rc2)), t2.rstrip())
    with open(out_path, "w") as f:
        f.write(_md("issues-sync stage: " + name, body))
    return 0


def cmd_apply_capture(opts, kw):
    buf = io.StringIO()
    rc = cmd_apply(opts, buf, kw)
    return rc, buf.getvalue()


def cmd_run(args, out, kw):
    ap = argparse.ArgumentParser(prog="run")
    ap.add_argument("--root", default=".")
    ap.add_argument("--write", action="store_true", help="docs_chain sync + pull --write (default: read-only doctor + verify)")
    a, rest = ap.parse_known_args(args)
    ctx = os.path.join(a.root, ".docs_chain", "contexts", CONTEXT_NAME + ".yaml")
    if not os.path.isfile(ctx):
        print("cannot determine: %s missing; run `init-context --root %s --owner-repo H/O/R --write`" % (ctx, a.root), file=out)
        return 2
    dc = find_docs_chain(os.environ)
    if not dc:
        print("cannot determine: docs_chain binary not found (set DOCS_CHAIN_BIN or put docs_chain on PATH; build: go build ./cmd/docs_chain in submodules/docs_chain)", file=out)
        return 2
    steps = [("doctor", [dc, "doctor", "--root", a.root, CONTEXT_NAME])]
    steps.append(("sync" if a.write else "verify", [dc, "sync" if a.write else "verify", "--root", a.root, CONTEXT_NAME]))
    rc = 0
    for label, cmd in steps:
        p = subprocess.run(cmd, capture_output=True, text=True)
        print("docs_chain %s: rc %d" % (label, p.returncode), file=out)
        if p.returncode != 0:         # doctor: invalid context (cannot proceed, 2); verify/sync: a stale or failed chain (1)
            print((p.stdout + p.stderr).strip()[-1500:], file=out)
            return 2 if label == "doctor" else 1
    if a.write:
        r, t = _capture(["pull", "--write"] + rest, **kw)
        print("pull --write: rc %d" % r, file=out); print(t.rstrip(), file=out)
        rc = max(rc, r)
    r, t = _capture(["verify"] + rest, **kw)
    print("verify: rc %d" % r, file=out); print(t.rstrip(), file=out)
    return 1 if (r == 1 or rc == 1) else max(r, rc)


def main(argv=None, out=sys.stdout, transport_factory=None, proven_hosts=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    kw = {"proven_hosts": proven_hosts}
    if transport_factory is not None:
        kw["transport_factory"] = transport_factory
    sp = split_exec_argv(argv)
    if sp:
        ins, outp, rest = sp
        return cmd_stage(rest[1:] if rest and rest[0] == "stage" else rest, outp, out, kw)
    if not argv or argv[0] not in SUBCOMMANDS or argv[0] == "stage":
        print("usage: issues_sync_pipeline.sh {plan|apply|pull|reconcile|verify|run|init-context} [options]  (dry-run default; exit 0 ok, 1 drift/refused, 2 cannot determine)", file=out)
        return 2
    cmd, rest = argv[0], argv[1:]
    if cmd == "apply":
        return cmd_apply(rest, out, kw)
    if cmd == "init-context":
        return cmd_init_context(rest, out)
    if cmd == "run":
        return cmd_run(rest, out, kw)
    return cli.run([cmd] + rest, out=out, **kw)


if __name__ == "__main__":
    sys.exit(main())
